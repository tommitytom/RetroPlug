// Derives the host transport (BPM + playing) from incoming MIDI real-time bytes, so an external clock
// master drives LSDj sync-to-external (the rp.lsdj.sync node regenerates 0xF8 from Engine tempo/transport
// with its own tick clock - it doesn't read the raw wire clock, so feeding setBpm/setTransport is all it takes).
// Audio-thread-only: fed from the audio callback's pull, never touched elsewhere → plain members, no locking.
//
// Clock timing: RtMidi timestamps are discarded and messages arrive block-quantized, so we measure the
// pulse rate in audio frames accumulated across blocks (24 PPQN): BPM = 60·sr·pulses / (frames·24). Playing
// follows 0xFA/0xFB (start/continue) and 0xFC (stop), plus a ~0.5 s clock-presence timeout so a bare-clock
// master with no start/stop still plays. With NO clock at all we fall back to a free-running 120/playing
// (the standalone's prior always-on behaviour), so non-sync use (mGB, un-synced LSDj) is unchanged.
struct MidiClockSync {
    double sampleRate = 48000.0;
    long long frameClock = 0;      // monotonic frames processed
    long long lastClockFrame = 0;  // frameClock at the most recent 0xF8
    long long windowFrames = 0;    // frames accumulated in the current tempo window
    int  windowPulses = 0;         // 0xF8 count in the current window
    double bpm = 120.0;            // last good estimate
    bool active = false;           // clock seen within the timeout
    bool stopped = false;          // explicit 0xFC latch (overrides clock presence)
    bool debug = false;            // RETROPLUG_DEBUG_AUDIO: report each tempo estimate's inputs
    std::uint64_t droppedMessages = 0;  // the stream's ring drops, folded in so the report names the culprit
    bool manualPlaying = false;    // the local transport (Instance menu > MIDI Clock); used when no clock master
    double manualBpm = 120.0;      // the local tempo, likewise — what the sync roles clock at when we're the master

    static constexpr int    kWindowPulses = 24; // one quarter-note → a stable estimate ~2×/s
    static constexpr double kTimeoutSec   = 0.5;
    // The tempo range an estimate is trusted in — also what the local tempo is clamped to, so a hand-set
    // tempo and a measured one can't disagree about what counts as legal.
    static constexpr double kMinBpm = 20.0;
    static constexpr double kMaxBpm = 999.0;

    // One drained real-time byte. Returns true if it was a transport byte (so the caller skips staging it).
    bool onByte(std::uint8_t status) {
        switch (status) {
            case 0xF8: active = true; lastClockFrame = frameClock; ++windowPulses; return true; // clock
            case 0xFA: case 0xFB: active = true; stopped = false; lastClockFrame = frameClock; return true; // start/continue
            case 0xFC: stopped = true; return true; // stop
            default: return false;
        }
    }

    // Call once per audio block, after that block's bytes, with the block's frame count.
    void advance(long long frames) {
        if (active) {
            windowFrames += frames;
            if (windowPulses >= kWindowPulses && windowFrames > 0) {
                const double est = 60.0 * sampleRate * windowPulses / (static_cast<double>(windowFrames) * 24.0);
                if (debug)
                    std::fprintf(stderr, "[retroplug-sdl] clock: %d pulses / %lld frames @ %.0f Hz -> %.1f BPM"
                                 " (%.1f pulses/s, %llu message(s) dropped)\n",
                                 windowPulses, windowFrames, sampleRate, est,
                                 sampleRate * windowPulses / static_cast<double>(windowFrames),
                                 static_cast<unsigned long long>(droppedMessages));
                if (est >= kMinBpm && est <= kMaxBpm) bpm = est;
                windowPulses = 0;
                windowFrames = 0;
            }
            if (frameClock - lastClockFrame > static_cast<long long>(sampleRate * kTimeoutSec)) {
                active = false; stopped = false; windowPulses = 0; windowFrames = 0; // master gone → free-run
            }
        }
        frameClock += frames;
    }

    double outBpm() const { return active ? bpm : manualBpm; }
    // An external master wins while it is there; otherwise the local transport decides. That local transport
    // starts STOPPED, which is a change from the standalone's original always-playing behaviour: a running
    // transport is not idle state, it is a clock — the LSDj/risa sync roles turn it into link-port bytes, so
    // a SYNC=MIDI cart used to start running at 120 BPM the moment it booted, with nothing plugged in and no
    // way to stop it. Non-sync use (mGB, an un-synced cart) never looked at the transport and is unaffected.
    bool   outPlaying() const { return active ? !stopped : manualPlaying; }

};

// Whole-process state, reached by the LVGL indev read callbacks (via driver_data), the SDL audio
// callback (via userdata), and the __rp_* window hooks (single instance → a file-scope pointer is fine,
// unlike the plugin's per-context routing for multi-instance DAWs).
struct AppState {
    // --- the shared runtime + backend graph (PluginDSP's control plane) ---
    TjsHostRuntime host;
    // Three facets only, same as the plugin's channel — no debug, no audio-driver. See
    // host/HostServices.hpp for why those two are not members rather than merely unmounted.
    HostServices   svc;
    std::unique_ptr<rpcpp::QuickJSTransport> transport;
    std::unique_ptr<BackendRpcServer>        server;

    // --- the UI display layer (PluginUI), on the SAME host ---
    LvglJsEngine  ui{host};   // external-host ctor: adds only the LVGL layer, never shuts host down
    lv_display_t* display = nullptr;
    std::vector<std::uint8_t> drawBuf;
    lv_group_t*   group = nullptr;
    lv_indev_t*   keypad = nullptr;
    lv_indev_t*   pointer = nullptr;

    // synthetic input state the shared keypad/pointer indev read callbacks pull from (driver_data == &input)
    retroplug::ui::LvInputState input;

    // A desktop file drag-and-drop in progress: SDL delivers one SDL_DROPFILE per file between
    // SDL_DROPBEGIN and SDL_DROPCOMPLETE, so we accumulate the paths here and emit one newline-joined
    // "file-drop" on complete (matching PluginUI::uiFileDropped — resolveDropAction needs ROM+.sav together).
    std::vector<std::string> dropBatch;

    // The in-flight OS-native file dialog (opened by __rp_openFileBrowser). Async: opened here, polled each
    // frame in the main loop (pollFileDialog), the pick delivered to JS on ready. Shared with the plugin host.
    retroplug::ui::NativeFileDialog nativeDialog;

    // --- SDL shell ---
    SDL_Window*   window = nullptr;
    SDL_Renderer* renderer = nullptr;
    SDL_Texture*  texture = nullptr;
    rp::audio::AudioHost* audio = nullptr;     // the device, its reconfigure and its muted fallback (main owns it)
    retroplug::GamepadManager gamepad;
    rp::midi::MidiStream midi{rp::midi::systemMidi()};  // in/out; drained into the Engine on the audio thread each block
    std::vector<rp::midi::MidiStream::Message> midiScratch;  // reused per block; reserved to the ring size in main()
    std::atomic<std::uint64_t> midiStaged{0};             // count staged into the Engine (headless self-test)
    MidiClockSync clockSync;                              // MIDI-clock → BPM/transport (audio thread only)

    // The local transport (Instance menu > Transport), across the UI/audio thread boundary. clockSync itself
    // is audio-thread-only, so the menu can't poke it: the UI writes the REQUEST, the callback folds it into
    // clockSync each block and publishes back what the transport actually is (an external clock master
    // overrides the local flag, and the menu shows that rather than lying about who is in charge).
    std::atomic<bool>  transportRequest{false};   // UI -> audio: the local play/stop the user picked
    std::atomic<float> clockBpmRequest{120.0f};   // UI -> audio: the local tempo (the project's `midi.clockBpm`)
    std::atomic<bool>  transportPlaying{false};   // audio -> UI: what the Engine is actually being told
    std::atomic<bool>  transportExternal{false};  // audio -> UI: a MIDI clock master is driving it
    std::atomic<float> transportBpm{120.0f};      // audio -> UI: the tempo in force (theirs when external)

    // The device links the graph's hardware nodes bind (rp.host.devices/2), and the facets beside them: the ones the
    // providers of this product's packages install and mount (the N8 pack's streaming link, n8.cfg and the cart link;
    // the Launchpad pack's control-surface link and its port facet). svc (the engine) is declared above them (the
    // providers read its config dir), so it is destroyed after all of them. The destructor below reclaims the plans
    // first, while every member is still alive: a node may use its handle in destroy, and it must reach a live link.
    // The engine has no plan left to destroy by then.
    //
    // The three control-surface calls a provider makes are this product's (rp_provider.h): the claimed pair leaves the
    // shared MIDI stream before it is opened, a scan steps the stream's hardware inputs aside, and MIDI and audio wait
    // for the control plane's restore (see the definitions beside startAudio/stopAudio).
    rp::host::ProviderHost deviceHost{svc.engine, svc.host.configDir(),
                                      rp::host::ProviderHost::Calls{this, &AppState::onReserveMidi,
                                                                    &AppState::onSuspendInputs, &AppState::onRestored}};
    rp::Providers          providers;  // started in main, before the control plane can publish a graph
    // RETROPLUG_IDLE_RECLAIM_TEST: inert unless the smoke arms it. Holds this loop to the idle tick it owes the
    // engine (HostServices::reclaimOnIdle), which no in-process test can reach.
    retroplug::IdleReclaimProbe idleProbe;
    // Whether the control plane has reported its restored selection yet. main() holds MIDI and audio until it is true
    // (waitForUiStartup, which also waits for the audio service's first apply), so a restored surface's claim lands
    // before the shared stream ever opens its ports; a claim that arrives later is reserved through the stream's own
    // handshake, which costs no audio stop either.
    bool controlSurfaceRestored = false;

    // Out of line in main.cpp, the one unit that includes the generated provider table: a unit that only uses AppState
    // reads no generated declaration.
    ~AppState();

    static bool onReserveMidi(void* ctx, const std::string& input, const std::string& output);
    static void onSuspendInputs(void* ctx, bool suspended);
    static void onRestored(void* ctx);

    std::uint32_t width = 640;
    std::uint32_t height = 480;
    bool running = true;
    // Fullscreen (the handheld): the WM owns a fixed panel, so the UI fits its grid via zoom and
    // __rp_setWindowSize is inert. Windowed (desktop): the window is ours to size, so it grows/shrinks to
    // the grid like the DPF standalone. Set from the SDL_WINDOW_FULLSCREEN flag in setupSdl.
    bool fullscreen = false;

    // Window-geometry ownership — mirrors PluginUI's wmControlled_ / sizeHonored_ / requestedW/H latch, so the
    // resizable SDL window behaves like the DPF standalone under a tiling WM (Wayland/Hyprland). wmControlled
    // starts true for fullscreen and for the Wayland backend (see setupSdl - a Wayland compositor never tells
    // us whether it honored a resize); it also latches true when the compositor hands us a size we never asked
    // for (a tile) before any requested size was ever honored - then we stop driving SDL_SetWindowSize and the
    // UI fits its grid via zoom instead. sizeHonored proves the window is floating (a request took), which
    // vetoes the clamp latch so a spurious compositor resize isn't mistaken for a tiling takeover.
    bool          wmControlled = false;
    bool          sizeHonored = false;
    std::uint32_t requestedW = 0;   // last size asked of the WM (the clamp-detection baseline)
    std::uint32_t requestedH = 0;
    bool          debugResize = false;  // RETROPLUG_DEBUG_RESIZE: log every request / WM resize (WM debugging)
    bool          logWheel = false;     // RETROPLUG_SDL_TEST_WHEEL: report each wheel event + whether it scrolled

    int    numOutputs = 2;         // what the device came up at (AudioHost prepared the engine for it)
    double sampleRate = 48000.0;   // obtained device rate (drives the Engine)
    int    reqSampleRate = 48000;  // the `audio` section's request: rate, block and width, saved with config.json
    int    reqBlockSize  = 512;    // low-latency default; a low-power device passes a bigger buffer, e.g. 4096, so the
                                   // audio callback keeps its deadline (`audio`'s block, or --block-size for one run)
    int    reqOutChannels = 2;     // 2 = stereo mix (default); 4/6/8 = wide stems for a multichannel device
    std::string backendOverride;   // --audio-backend / RETROPLUG_SDL_AUDIO_BACKEND: this RUN's backend, which no saved
                                   // or UI choice may move (the Settings row's Apply sets reqBackend, not this)
    int blockSizeOverride = 0;     // --block-size: this RUN's block, which no saved choice may move (E12)
    // Whether TypeScript has applied the `audio` section yet. The startup rendezvous waits for it (or its bound), so the
    // device opens with what config.json saved rather than before the control plane can know it. The apply RECORDS the
    // request; the host opens the device at its own point (main, after the MIDI stream and the providers' restore), and
    // from then on a UI apply is live - which is what audioDeviceReady says.
    bool audioApplied = false;
    bool audioDeviceReady = false;
    std::string reqBackend;        // the backend the saved choice names ("" = auto): --audio-backend's
    std::string reqDriver;         // the driver's ID in that backend's vocabulary ("" = its auto driver)
    std::string reqOutputDevice;   // the device's NAME ("" = the driver's default device), from the `audio` section.
    int    renderAhead = 0;        // frames the render thread keeps queued (--render-ahead / RETROPLUG_SDL_RENDER_AHEAD)
    // audio scratch: `numOutputs` planar channel buffers (sized by prepare, so a block never allocates). The Engine
    // renders planar and routes each system to its pair per audioRouting; render() interleaves into the device's
    // buffer. numOutputs is what the device came up at, which the engine was shaped for.
    std::vector<std::vector<float>> audioPlanar;
    std::vector<float*>             audioPtrs;

    // Present only when LVGL actually redrew: the flush cb unions the changed area here; the loop skips
    // the SDL texture upload + blit entirely on idle frames (a static menu → ~0% CPU instead of a full
    // 640×480 upload every frame). dirty starts true so the first frame always shows.
    bool dirty = true;
    lv_area_t dirtyRect{0, 0, 0, 0};
};

