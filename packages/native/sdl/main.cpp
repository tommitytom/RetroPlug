bool bootControlPlane(AppState& a) {
    if (!a.host.init()) { std::fprintf(stderr, "[retroplug-sdl] TjsHostRuntime init failed\n"); return false; }
    JSContext* ctx = a.host.context();

    registerCoreBackends(a.factory);

    a.transport = std::make_unique<rpcpp::QuickJSTransport>(ctx, [](JSContext*, JSValue) {});
    a.server    = std::make_unique<BackendRpcServer>(*a.transport, rpcpp::QuickJSCodec{ctx});
    registerHostRpc(*a.server, a.hostSvc);
    registerEmulatorRpc(*a.server, a.engineSvc);
    registerDspKernelRpc(*a.server, a.engineSvc);
    a.server->addDiscoveryMethod();

    // globalThis[Symbol.for("plugin")] = { __rpcSend } — the namespace realBackend.ts targets.
    JSValue global = JS_GetGlobalObject(ctx);
    JSValue sym    = JS_NewSymbol(ctx, "plugin", /*is_global*/ 1);
    JSAtom atom    = JS_ValueToAtom(ctx, sym);
    JSValue ns     = JS_NewObjectProto(ctx, JS_NULL);
    BackendRpcServer* srv = a.server.get();
    a.host.bindRpcSend(ns, [srv](JSContext* sctx, JSValueConst req) -> JSValue {
        auto out = srv->processMessage(req);
        if (!out) return JS_NULL;
        return out->materialize(sctx);
    });
    JS_DefinePropertyValue(ctx, global, atom, ns, JS_PROP_C_W_E);
    JS_FreeAtom(ctx, atom);
    JS_FreeValue(ctx, sym);
    JS_FreeValue(ctx, global);

    // Systems bake the sample rate at construct — set it BEFORE the bundle composes / autoloads.
    a.engine.setSampleRate(a.sampleRate);

    a.host.evalModuleBytecode(rp_cp_bundle, rp_cp_bundle_size);
    for (int i = 0; i < 1000 && !readReady(a.host); ++i) a.host.pump();
    if (!readReady(a.host)) { std::fprintf(stderr, "[retroplug-sdl] control plane not ready\n"); return false; }
    return true;
}

bool setupUi(AppState& a) {
    lv_init();
    lv_tick_set_cb(sdlTicksCb);

    // Display + indevs: the shared software-LVGL scaffold (host/ui/SoftwareLvglDisplay.hpp), also used by the
    // headless test harness. SDL supplies its own dirty-tracking flush (present() uploads only the changed rect).
    auto sd = retroplug::ui::createSoftwareDisplay(a.width, a.height, a.drawBuf, flushCb, &a.input);
    if (!sd.display) return false;
    a.display = sd.display;
    a.group   = sd.group;
    a.keypad  = sd.keypad;
    a.pointer = sd.pointer;

    if (!a.ui.init()) { std::fprintf(stderr, "[retroplug-sdl] LvglJsEngine init failed\n"); return false; }

    JSContext* ctx = a.ui.getContext();
    if (ctx && !hasGlobalFunction(ctx, "__rp_mountUI")) {
        if (a.ui.evalModuleBytecode(rp_ui_bundle, rp_ui_bundle_size) != 0) {
            std::fprintf(stderr, "[retroplug-sdl] failed to eval UI bundle\n");
            return false;
        }
    }
    a.ui.attachDisplay(); // → __rp_mountUI

    // Black screen, stripped chrome, root pinned to 100% — same as PluginUI (shared with the test harness).
    retroplug::ui::applyChromelessScreen();
    if (ctx) installWindowHooks(ctx);
    return true;
}

bool setupSdl(AppState& a) {
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_AUDIO | SDL_INIT_GAMECONTROLLER) != 0) {
        std::fprintf(stderr, "[retroplug-sdl] SDL_Init failed: %s\n", SDL_GetError());
        return false;
    }
    Uint32 winFlags = 0;
    if (std::getenv("RETROPLUG_SDL_FULLSCREEN")) winFlags |= SDL_WINDOW_FULLSCREEN;
    a.fullscreen = (winFlags & SDL_WINDOW_FULLSCREEN) != 0; // gates the __rp_setWindowSize resize seam
    a.window = SDL_CreateWindow("RetroPlug", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
                                a.width, a.height, winFlags);
    if (!a.window) { std::fprintf(stderr, "[retroplug-sdl] SDL_CreateWindow failed: %s\n", SDL_GetError()); return false; }
    a.renderer = SDL_CreateRenderer(a.window, -1, SDL_RENDERER_SOFTWARE);
    if (!a.renderer) { std::fprintf(stderr, "[retroplug-sdl] SDL_CreateRenderer failed: %s\n", SDL_GetError()); return false; }
    a.texture = SDL_CreateTexture(a.renderer, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STREAMING,
                                  a.width, a.height);
    if (!a.texture) { std::fprintf(stderr, "[retroplug-sdl] SDL_CreateTexture failed: %s\n", SDL_GetError()); return false; }

    // Audio: apply any persisted rate/block (the Audio settings submenu) then open before boot so the
    // obtained rate seeds the Engine. The dummy driver (headless) still fires the callback, so the
    // emulator advances even with no device.
    loadAudioConfig(a);
    openAudio(a);
    return true;
}

void present(AppState& a) {
    if (!a.dirty) return; // nothing redrew this frame — leave the screen as-is (huge idle CPU saving)
    const int stride = static_cast<int>(lv_draw_buf_width_to_stride(a.width, lv_display_get_color_format(a.display)));
    // Upload only the changed region (clamped) from the draw buffer; the streaming texture keeps the rest.
    int x1 = std::max(0, (int)a.dirtyRect.x1), y1 = std::max(0, (int)a.dirtyRect.y1);
    int x2 = std::min((int)a.width - 1, (int)a.dirtyRect.x2), y2 = std::min((int)a.height - 1, (int)a.dirtyRect.y2);
    if (x2 >= x1 && y2 >= y1) {
        SDL_Rect rect{x1, y1, x2 - x1 + 1, y2 - y1 + 1};
        const std::uint8_t* src = a.drawBuf.data() + static_cast<std::size_t>(y1) * stride + static_cast<std::size_t>(x1) * 4;
        SDL_UpdateTexture(a.texture, &rect, src, stride);
    }
    SDL_RenderCopy(a.renderer, a.texture, nullptr, nullptr);
    SDL_RenderPresent(a.renderer);
    a.dirty = false;
}

// Resize the window and every dimension-tracking resource in lockstep: the SDL window, the LVGL display
// resolution + its DIRECT-mode draw buffer, and the streaming SDL texture (a STREAMING texture can't resize
// in place — recreate it). Then force a full-window redraw and tell the UI so it re-lays-out. This inlines
// what DPF's platform resize callback does for the plugin (LVGL::recreateTextureData + emit "resize").
void resizeWindow(AppState& a, std::uint32_t w, std::uint32_t h) {
    if (!a.window || !a.display || !a.renderer) return;

    SDL_SetWindowSize(a.window, static_cast<int>(w), static_cast<int>(h));

    // LVGL display: set the new resolution, then re-point it at a freshly sized DIRECT buffer.
    const lv_color_format_t cf = lv_display_get_color_format(a.display);
    const std::uint32_t stride = lv_draw_buf_width_to_stride(w, cf);
    a.drawBuf.assign(static_cast<std::size_t>(stride) * h, 0);
    lv_display_set_resolution(a.display, w, h);
    lv_display_set_buffers(a.display, a.drawBuf.data(), nullptr, a.drawBuf.size(), LV_DISPLAY_RENDER_MODE_DIRECT);

    // SDL streaming texture: recreate at the new size (can't be resized in place).
    if (a.texture) SDL_DestroyTexture(a.texture);
    a.texture = SDL_CreateTexture(a.renderer, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STREAMING,
                                  static_cast<int>(w), static_cast<int>(h));

    a.width = w;
    a.height = h;
    a.dirty = true; // present the whole new surface next frame (lv_timer_handler redraws into the new buffer)
    a.dirtyRect = {0, 0, static_cast<std::int32_t>(w) - 1, static_cast<std::int32_t>(h) - 1};

    if (JSContext* ctx = a.ui.getContext()) { // mirror PluginUI::onResize → the UI re-reads Dimensions.window
        JSValue args[2] = {JS_NewUint32(ctx, w), JS_NewUint32(ctx, h)};
        a.ui.emit("resize", 2, args);
        JS_FreeValue(ctx, args[0]);
        JS_FreeValue(ctx, args[1]);
    }
}

void handleEvents(AppState& a) {
    SDL_Event ev;
    while (SDL_PollEvent(&ev)) {
        switch (ev.type) {
            // OS window-close (window button / WM / Ctrl-C) → route through the unsaved-changes guard, exactly
            // as the DPF standalone's PluginUI::onClose does (and the Exit menu row already does via JS). The
            // JS guard returns true to veto (it raises the save prompt and later calls __rp_quitWindow itself
            // once the user confirms Save/Discard); false = clean project, quit now. Without this, closing a
            // dirty project by the window button would skip the prompt and lose work.
            case SDL_QUIT: {
                bool veto = false;
                if (JSContext* ctx = a.ui.getContext()) {
                    JSValue global = JS_GetGlobalObject(ctx);
                    JSValue fn     = JS_GetPropertyStr(ctx, global, "__rp_onCloseRequested");
                    if (JS_IsFunction(ctx, fn)) {
                        JSValue ret = JS_Call(ctx, fn, JS_UNDEFINED, 0, nullptr);
                        veto = JS_ToBool(ctx, ret) == 1;
                        JS_FreeValue(ctx, ret);
                    }
                    JS_FreeValue(ctx, fn);
                    JS_FreeValue(ctx, global);
                }
                if (!veto) a.running = false;
                break;
            }
            // Desktop drag-and-drop → the "file-drop" JS bus (mirrors PluginUI::uiFileDropped). SDL2's
            // SDL_DropEvent carries no coordinates (the x/y fields are SDL3-only) and one path per event, so
            // we batch across begin→complete and read the cursor ourselves for the tile hit-test.
            case SDL_DROPBEGIN: a.dropBatch.clear(); break;
            case SDL_DROPFILE:
                if (ev.drop.file) { a.dropBatch.emplace_back(ev.drop.file); SDL_free(ev.drop.file); }
                break;
            case SDL_DROPCOMPLETE:
                if (JSContext* ctx = a.ui.getContext(); ctx && !a.dropBatch.empty()) {
                    std::string joined;
                    for (const std::string& p : a.dropBatch) { if (!joined.empty()) joined += '\n'; joined += p; }
                    int mx = 0, my = 0;
                    SDL_GetMouseState(&mx, &my); // window-pixel space — the coords hitTestTile expects (best-effort)
                    JSValue args[3] = {JS_NewString(ctx, joined.c_str()),
                                       JS_NewFloat64(ctx, mx), JS_NewFloat64(ctx, my)};
                    a.ui.emit("file-drop", 3, args);
                    for (JSValue& v : args) JS_FreeValue(ctx, v);
                }
                a.dropBatch.clear();
                break;
            case SDL_KEYDOWN:
            case SDL_KEYUP: {
                std::uint32_t lv, dpf;
                if (mapSdlKey(ev.key.keysym.sym, lv, dpf)) feedKey(a, lv, dpf, ev.type == SDL_KEYDOWN);
                break;
            }
            case SDL_MOUSEMOTION: a.input.mousePos = {ev.motion.x, ev.motion.y}; break;
            case SDL_MOUSEBUTTONDOWN:
            case SDL_MOUSEBUTTONUP:
                a.input.mousePos = {ev.button.x, ev.button.y};
                a.input.mouseDown = ev.type == SDL_MOUSEBUTTONDOWN;
                break;
            default: break;
        }
    }
}

