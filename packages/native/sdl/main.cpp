bool readReady(TjsHostRuntime& host) {
    JSContext* ctx = host.context();
    JSValue g = JS_GetGlobalObject(ctx);
    JSValue v = JS_GetPropertyStr(ctx, g, "__rp_ready");
    const bool r = JS_ToBool(ctx, v) > 0;
    JS_FreeValue(ctx, v);
    JS_FreeValue(ctx, g);
    return r;
}

// Call globalThis[name](arg?) on the control-plane context (main thread). Returns the string result, or
// "" for non-string / missing / exception. Mirrors PluginDSP::callGlobal (used for autoload here).
std::string callGlobal(TjsHostRuntime& host, const char* name, const char* arg) {
    JSContext* ctx = host.context();
    JSValue g  = JS_GetGlobalObject(ctx);
    JSValue fn = JS_GetPropertyStr(ctx, g, name);
    std::string out;
    if (JS_IsFunction(ctx, fn)) {
        JSValue argv[1];
        int argc = 0;
        if (arg) { argv[0] = JS_NewString(ctx, arg); argc = 1; }
        JSValue ret = JS_Call(ctx, fn, g, argc, argc ? argv : nullptr);
        if (argc) JS_FreeValue(ctx, argv[0]);
        if (JS_IsException(ret)) {
            JSValue exc = JS_GetException(ctx);
            const char* s = JS_ToCString(ctx, exc);
            std::fprintf(stderr, "[retroplug-sdl] %s threw: %s\n", name, s ? s : "?");
            if (s) JS_FreeCString(ctx, s);
            JS_FreeValue(ctx, exc);
        } else if (JS_IsString(ret)) {
            const char* s = JS_ToCString(ctx, ret);
            if (s) { out = s; JS_FreeCString(ctx, s); }
        } else if (JS_IsBool(ret)) {
            out = JS_ToBool(ctx, ret) > 0 ? "true" : "false";
        }
        JS_FreeValue(ctx, ret);
    }
    JS_FreeValue(ctx, fn);
    JS_FreeValue(ctx, g);
    return out;
}

bool hasGlobalFunction(JSContext* ctx, const char* name) {
    JSValue g = JS_GetGlobalObject(ctx);
    JSValue v = JS_GetPropertyStr(ctx, g, name);
    const bool ok = JS_IsFunction(ctx, v);
    JS_FreeValue(ctx, v);
    JS_FreeValue(ctx, g);
    return ok;
}

// ---- native file browser ---------------------------------------------------------------------------

// Report the pick (or null on cancel) back to the UI via the resolver realBackend.ts installed.
void fbResult(AppState& a, const char* path) {
    JSContext* ctx = a.ui.getContext();
    if (!ctx) return;
    JSValue g  = JS_GetGlobalObject(ctx);
    JSValue fn = JS_GetPropertyStr(ctx, g, "__rp_onFileBrowserResult");
    if (JS_IsFunction(ctx, fn)) {
        JSValue arg = path ? JS_NewString(ctx, path) : JS_NULL;
        JSValue ret = JS_Call(ctx, fn, JS_UNDEFINED, 1, &arg);
        JS_FreeValue(ctx, ret);
        JS_FreeValue(ctx, arg);
    }
    JS_FreeValue(ctx, fn);
    JS_FreeValue(ctx, g);
}

bool fbMatches(const std::string& name, const std::vector<std::string>& pats) {
    if (pats.empty()) return true;
    for (const auto& p : pats)
        if (fnmatch(p.c_str(), name.c_str(), FNM_CASEFOLD) == 0) return true;
    return false;
}

void fbHighlight(AppState& a) {
    for (int i = 0; i < (int)a.fb.rows.size(); ++i) {
        lv_obj_t* r = a.fb.rows[i];
        if (i == a.fb.sel) {
            lv_obj_set_style_bg_color(r, lv_color_hex(0x1e5aa8), 0);
            lv_obj_set_style_bg_opa(r, LV_OPA_COVER, 0);
            lv_obj_scroll_to_view(r, LV_ANIM_OFF);
        } else {
            lv_obj_set_style_bg_opa(r, LV_OPA_TRANSP, 0);
        }
    }
}

void fbPopulate(AppState& a) {
    if (a.fb.list) lv_obj_clean(a.fb.list);
    a.fb.entries.clear();
    a.fb.rows.clear();

    if (a.fb.dir != "/") a.fb.entries.push_back({"..", true});

    std::vector<Entry> dirs, files;
    if (DIR* d = opendir(a.fb.dir.c_str())) {
        while (struct dirent* e = readdir(d)) {
            std::string n = e->d_name;
            if (n == "." || n == ".." || (!n.empty() && n[0] == '.')) continue; // skip . .. hidden
            struct stat st;
            const std::string full = a.fb.dir + "/" + n;
            const bool isdir = stat(full.c_str(), &st) == 0 && S_ISDIR(st.st_mode);
            if (isdir) dirs.push_back({n, true});
            else if (fbMatches(n, a.fb.patterns)) files.push_back({n, false});
        }
        closedir(d);
    }
    const auto byName = [](const Entry& x, const Entry& y) { return x.name < y.name; };
    std::sort(dirs.begin(), dirs.end(), byName);
    std::sort(files.begin(), files.end(), byName);
    a.fb.entries.insert(a.fb.entries.end(), dirs.begin(), dirs.end());
    a.fb.entries.insert(a.fb.entries.end(), files.begin(), files.end());

    for (const Entry& en : a.fb.entries) {
        const char* icon = en.isDir ? LV_SYMBOL_DIRECTORY : LV_SYMBOL_FILE;
        const std::string label = en.name + (en.isDir && en.name != ".." ? "/" : "");
        lv_obj_t* btn = lv_list_add_button(a.fb.list, icon, label.c_str());
        lv_obj_set_style_radius(btn, 0, 0);
        lv_obj_set_style_border_width(btn, 0, 0);
        a.fb.rows.push_back(btn);
    }
    a.fb.sel = 0;
    if (a.fb.titleLabel)
        lv_label_set_text(a.fb.titleLabel, (a.fb.title + "   " + a.fb.dir).c_str());
    fbHighlight(a);
}

void fbClose(AppState& a) {
    if (a.fb.overlay) { lv_obj_delete(a.fb.overlay); a.fb.overlay = nullptr; }
    a.fb.list = nullptr; a.fb.titleLabel = nullptr;
    a.fb.rows.clear(); a.fb.entries.clear();
    a.fb.active = false;
}

void fbOpen(AppState& a, const char* title, const char* patternsStr, bool saving) {
    if (a.fb.active) return; // one dialog at a time
    a.fb.title  = (title && *title) ? title : "Select file";
    a.fb.saving = saving;
    a.fb.patterns.clear();
    if (patternsStr) { // split on whitespace
        std::string cur;
        for (const char* p = patternsStr; *p; ++p) {
            if (*p == ' ' || *p == '\t') { if (!cur.empty()) { a.fb.patterns.push_back(cur); cur.clear(); } }
            else cur += *p;
        }
        if (!cur.empty()) a.fb.patterns.push_back(cur);
    }
    const auto isdir = [](const char* p) { struct stat st; return stat(p, &st) == 0 && S_ISDIR(st.st_mode); };
    if (isdir("/mnt/mmc/ROMS")) a.fb.dir = "/mnt/mmc/ROMS";
    else if (isdir("/mnt/mmc")) a.fb.dir = "/mnt/mmc";
    else if (const char* h = std::getenv("HOME"); h && isdir(h)) a.fb.dir = h;
    else a.fb.dir = "/";

    lv_obj_t* top = lv_layer_top();
    a.fb.overlay = lv_obj_create(top);
    lv_obj_remove_style_all(a.fb.overlay);
    lv_obj_set_size(a.fb.overlay, lv_pct(100), lv_pct(100));
    lv_obj_set_style_bg_color(a.fb.overlay, lv_color_hex(0x000000), 0);
    lv_obj_set_style_bg_opa(a.fb.overlay, LV_OPA_COVER, 0);
    lv_obj_set_flex_flow(a.fb.overlay, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_style_pad_all(a.fb.overlay, 4, 0);

    a.fb.titleLabel = lv_label_create(a.fb.overlay);
    lv_obj_set_style_text_color(a.fb.titleLabel, lv_color_hex(0x4aa3ff), 0);
    lv_label_set_long_mode(a.fb.titleLabel, LV_LABEL_LONG_DOT);
    lv_obj_set_width(a.fb.titleLabel, lv_pct(100));

    a.fb.list = lv_list_create(a.fb.overlay);
    lv_obj_set_width(a.fb.list, lv_pct(100));
    lv_obj_set_flex_grow(a.fb.list, 1);
    lv_obj_set_style_bg_color(a.fb.list, lv_color_hex(0x000000), 0);
    lv_obj_set_style_border_width(a.fb.list, 0, 0);
    lv_obj_set_style_pad_all(a.fb.list, 0, 0);

    a.fb.active = true;
    fbPopulate(a);
}

void fbMove(AppState& a, int delta) {
    if (a.fb.entries.empty()) return;
    a.fb.sel = std::max(0, std::min((int)a.fb.entries.size() - 1, a.fb.sel + delta));
    fbHighlight(a);
}

void fbActivate(AppState& a) {
    if (a.fb.entries.empty()) return;
    const Entry en = a.fb.entries[a.fb.sel];
    if (en.name == "..") {
        const auto slash = a.fb.dir.find_last_of('/');
        a.fb.dir = (slash == 0 || slash == std::string::npos) ? "/" : a.fb.dir.substr(0, slash);
        fbPopulate(a);
        return;
    }
    const std::string full = (a.fb.dir == "/" ? std::string() : a.fb.dir) + "/" + en.name;
    if (en.isDir) { a.fb.dir = full; fbPopulate(a); return; }
    fbResult(a, full.c_str()); // a file — report + close
    fbClose(a);
}

void fbCancel(AppState& a) { fbResult(a, nullptr); fbClose(a); }

// Feed a gamepad button (raw SDL name) to the browser while it's open. Returns true (always consumes
// input while active). dpad = move, A = enter/descend, B = up/cancel.
void fbGamepad(AppState& a, const char* name, bool pressed) {
    if (!pressed || !name) return;
    if (!std::strcmp(name, "dpup"))        fbMove(a, -1);
    else if (!std::strcmp(name, "dpdown")) fbMove(a, 1);
    else if (!std::strcmp(name, "dpleft")) fbMove(a, -8); // page up
    else if (!std::strcmp(name, "dpright"))fbMove(a, 8);  // page down
    else if (!std::strcmp(name, "a"))      fbActivate(a);
    else if (!std::strcmp(name, "b")) {
        if (a.fb.dir != "/" && a.fb.dir != "/mnt/mmc" && a.fb.dir != "/mnt/mmc/ROMS") {
            // go up a level (B doubles as "up"); cancel only at the start dir
            const auto slash = a.fb.dir.find_last_of('/');
            a.fb.dir = (slash == 0 || slash == std::string::npos) ? "/" : a.fb.dir.substr(0, slash);
            fbPopulate(a);
        } else {
            fbCancel(a);
        }
    }
}

// ---- __rp_* window hooks (PluginUI's window-op seam, single-instance) ------------------------------
// The UI optional-chains these, so anything we omit is simply inert. We provide the handful a handheld
// standalone needs; the render-job hooks are left to a later milestone.

JSValue jsQuitWindow(JSContext*, JSValueConst, int, JSValueConst*) {
    if (g_app) g_app->running = false;
    return JS_UNDEFINED;
}
// Report the window as WM-controlled so the UI fits its grid via zoom instead of trying to resize a
// fixed fullscreen handheld window.
JSValue jsIsWindowSizeControlled(JSContext* ctx, JSValueConst, int, JSValueConst*) { return JS_NewBool(ctx, 1); }
JSValue jsSetWindowSize(JSContext*, JSValueConst, int, JSValueConst*) { return JS_UNDEFINED; }
JSValue jsSetWindowTitle(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (g_app && g_app->window && argc >= 1) {
        const char* t = JS_ToCString(ctx, argv[0]);
        if (t && *t) SDL_SetWindowTitle(g_app->window, t);
        if (t) JS_FreeCString(ctx, t);
    }
    return JS_UNDEFINED;
}
JSValue jsOpenPath(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (argc >= 1) {
        const char* p = JS_ToCString(ctx, argv[0]);
        if (p && *p) { const std::string cmd = "xdg-open \"" + std::string(p) + "\" &"; (void)std::system(cmd.c_str()); }
        if (p) JS_FreeCString(ctx, p);
    }
    return JS_UNDEFINED;
}

// __rp_getAudioConfig(): { sampleRate, blockSize } — the live standalone audio device config, for the
// Audio settings submenu to display the current values.
JSValue jsGetAudioConfig(JSContext* ctx, JSValueConst, int, JSValueConst*) {
    JSValue o = JS_NewObject(ctx);
    if (g_app) {
        JS_SetPropertyStr(ctx, o, "sampleRate", JS_NewInt32(ctx, g_app->reqSampleRate));
        JS_SetPropertyStr(ctx, o, "blockSize",  JS_NewInt32(ctx, g_app->reqBlockSize));
    }
    return o;
}

// __rp_setAudioConfig(sampleRate, blockSize): re-open the audio device with new params on the fly (and
// persist them). Reuses the deactivate→re-rate→reactivate handoff the plugin does for a host SR change.
JSValue jsSetAudioConfig(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (g_app && argc >= 2) {
        int sr = 0, bs = 0;
        JS_ToInt32(ctx, &sr, argv[0]);
        JS_ToInt32(ctx, &bs, argv[1]);
        if (sr > 0 && bs > 0) reconfigureAudio(*g_app, sr, bs);
    }
    return JS_UNDEFINED;
}

// __rp_openFileBrowser(title, patterns, saving, defaultName): open the native on-screen picker. The pick
// arrives later via __rp_onFileBrowserResult (matches the plugin's DPF dialog seam).
JSValue jsOpenFileBrowser(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (!g_app || argc < 3) return JS_UNDEFINED;
    const char* title    = JS_ToCString(ctx, argv[0]);
    const char* patterns = JS_ToCString(ctx, argv[1]);
    const int   saving   = JS_ToBool(ctx, argv[2]);
    fbOpen(*g_app, title ? title : "", patterns ? patterns : "", saving == 1);
    if (title) JS_FreeCString(ctx, title);
    if (patterns) JS_FreeCString(ctx, patterns);
    return JS_UNDEFINED;
}

void installWindowHooks(JSContext* ctx) {
    JSValue g = JS_GetGlobalObject(ctx);
    auto bind = [&](const char* name, JSCFunction* fn, int len) {
        JS_SetPropertyStr(ctx, g, name, JS_NewCFunction(ctx, fn, name, len));
    };
    bind("__rp_quitWindow", jsQuitWindow, 0);
    bind("__rp_isWindowSizeControlled", jsIsWindowSizeControlled, 0);
    bind("__rp_setWindowSize", jsSetWindowSize, 2);
    bind("__rp_setWindowTitle", jsSetWindowTitle, 1);
    bind("__rp_openPath", jsOpenPath, 1);
    bind("__rp_openFileBrowser", jsOpenFileBrowser, 4);
    bind("__rp_getAudioConfig", jsGetAudioConfig, 0);
    bind("__rp_setAudioConfig", jsSetAudioConfig, 2);
    // Mark this as a standalone host so the UI shows the "Exit" menu row (a DAW hides it).
    JS_SetPropertyStr(ctx, g, "__rp_isStandalone", JS_NewBool(ctx, 1));
    JS_FreeValue(ctx, g);
}

// ---- input translation ----------------------------------------------------------------------------

// Push an LVGL key onto the keypad queue AND emit the "key" JS bus (press+release), mirroring
// RenderCore::tapKey / PluginUI::onKeyboard. dpf is the DPF keycode the TS input layer expects.
void feedKey(AppState& a, std::uint32_t lvKey, std::uint32_t dpf, bool press) {
    JSContext* ctx = a.ui.getContext();
    if (press) a.keyQueue.push_back(lvKey);
    if (ctx) {
        JSValue args[2] = {JS_NewUint32(ctx, dpf), JS_NewBool(ctx, press)};
        a.ui.emit("key", 2, args);
        JS_FreeValue(ctx, args[0]);
        JS_FreeValue(ctx, args[1]);
    }
}

// Map an SDL keysym to (LVGL key, DPF keycode). Returns false for keys we don't translate.
bool mapSdlKey(SDL_Keycode k, std::uint32_t& lv, std::uint32_t& dpf) {
    switch (k) {
        case SDLK_UP:     lv = LV_KEY_UP;    dpf = 0xE036; return true;
        case SDLK_DOWN:   lv = LV_KEY_DOWN;  dpf = 0xE038; return true;
        case SDLK_RIGHT:  lv = LV_KEY_RIGHT; dpf = 0xE037; return true;
        case SDLK_LEFT:   lv = LV_KEY_LEFT;  dpf = 0xE035; return true;
        case SDLK_RETURN: lv = LV_KEY_ENTER; dpf = 0x0D;   return true;
        case SDLK_ESCAPE: lv = LV_KEY_ESC;   dpf = 0x1B;   return true;
        default: return false;
    }
}

// Poll controllers once per frame → re-emit each transition onto the gamepad-* JS bus (exactly as
// PluginUI::pumpGamepad). The gamepad drives BOTH menu navigation and in-game input purely through this
// bus: the React Menu has its own gamepad handler, and the design contract is that the gamepad bus never
// reaches the LVGL keypad indev (Menu.tsx). So we must NOT also translate gamepad → keypad here — doing
// so double-drives the menu (every move counted twice) while leaving in-game input single (the keypad
// keys hit the idle focus sink). Keyboard still feeds the keypad (mapSdlKey/feedKey) for desktop use.
void pumpGamepad(AppState& a) {
    JSContext* ctx = a.ui.getContext();
    if (!ctx) return;
    a.gamepad.update([&a, ctx](const retroplug::GamepadEvent& ev) {
        // While the native file browser is open it owns all input — drive it and never reach the React UI.
        if (a.fb.active) {
            if (ev.kind == retroplug::GamepadEvent::Kind::Button) fbGamepad(a, ev.button, ev.pressed);
            return;
        }
        switch (ev.kind) {
            case retroplug::GamepadEvent::Kind::Connected: {
                JSValue args[2] = {JS_NewInt32(ctx, ev.pad), JS_NewString(ctx, ev.name ? ev.name : "")};
                a.ui.emit("gamepad-connected", 2, args);
                JS_FreeValue(ctx, args[0]); JS_FreeValue(ctx, args[1]);
                break;
            }
            case retroplug::GamepadEvent::Kind::Disconnected: {
                JSValue args[1] = {JS_NewInt32(ctx, ev.pad)};
                a.ui.emit("gamepad-disconnected", 1, args);
                JS_FreeValue(ctx, args[0]);
                break;
            }
            case retroplug::GamepadEvent::Kind::Button: {
                JSValue args[3] = {JS_NewInt32(ctx, ev.pad), JS_NewString(ctx, ev.button ? ev.button : ""),
                                   JS_NewBool(ctx, ev.pressed)};
                a.ui.emit("gamepad-button", 3, args);
                JS_FreeValue(ctx, args[0]); JS_FreeValue(ctx, args[1]); JS_FreeValue(ctx, args[2]);
                break;
            }
            case retroplug::GamepadEvent::Kind::Axis: {
                JSValue args[3] = {JS_NewInt32(ctx, ev.pad), JS_NewString(ctx, ev.axis ? ev.axis : ""),
                                   JS_NewFloat64(ctx, ev.value)};
                a.ui.emit("gamepad-axis", 3, args);
                JS_FreeValue(ctx, args[0]); JS_FreeValue(ctx, args[1]); JS_FreeValue(ctx, args[2]);
                break;
            }
        }
    });
}

// ---- audio-thread scheduling (A53 real-time headroom) ----------------------------------------------
#if defined(__linux__)
// The audio path runs at ~1x realtime on the A53 (the SameBoy APU is ~92% of every block), so a
// preempted or core-shared audio thread underruns → choppy sound. Give the audio thread a dedicated core
// + real-time priority, and keep the UI/emulator-advancing work off that core. Best-effort: failures (no
// RT permission when not root) are ignored — it just falls back to the default scheduling.
void tuneAudioThread() {
    const long ncpu = sysconf(_SC_NPROCESSORS_ONLN);
    if (ncpu > 1) {
        cpu_set_t set; CPU_ZERO(&set); CPU_SET(ncpu - 1, &set); // pin to the last core
        pthread_setaffinity_np(pthread_self(), sizeof(set), &set);
    }
    sched_param sp{}; sp.sched_priority = 80;
    pthread_setschedparam(pthread_self(), SCHED_FIFO, &sp);
}
void pinUiThreadAwayFromAudioCore() {
    const long ncpu = sysconf(_SC_NPROCESSORS_ONLN);
    if (ncpu <= 2) return; // too few cores to segregate
    cpu_set_t set; CPU_ZERO(&set);
    for (long c = 0; c + 1 < ncpu; ++c) CPU_SET(c, &set); // all cores except the audio core (the last)
    pthread_setaffinity_np(pthread_self(), sizeof(set), &set);
}
#endif

// ---- audio ----------------------------------------------------------------------------------------
// SDL calls this on its own audio thread. It owns the Engine while running (setAudioThreadOwns(true)),
// so it drains the control-thread command ring each block then renders — mirrors PluginDSP::run.
void audioCb(void* userdata, Uint8* stream, int len) {
    auto* a = static_cast<AppState*>(userdata);
#if defined(__linux__)
    static std::atomic<bool> tuned{false};
    if (!tuned.exchange(true)) tuneAudioThread(); // once, on the real audio thread
#endif
    const int frames = len / static_cast<int>(2 * sizeof(float));
    if (frames <= 0) { std::memset(stream, 0, len); return; }
    if (static_cast<int>(a->audioL.size()) < frames) { a->audioL.resize(frames); a->audioR.resize(frames); }

    a->invoker.drainInto(a->engine);
    a->engine.setBpm(120.0);
    a->engine.setTransport(true);
    a->engine.processBlock(static_cast<std::uint32_t>(frames), a->audioL.data(), a->audioR.data());

    auto* out = reinterpret_cast<float*>(stream);
    for (int i = 0; i < frames; ++i) { out[2 * i] = a->audioL[i]; out[2 * i + 1] = a->audioR[i]; }
}

// Open the SDL audio device at the requested rate/block + size the render scratch. No frequency-change
// flag → the device opens at exactly reqSampleRate (PipeWire resamples), so the value the UI shows is
// truthful. Returns false (and the app runs muted) if the device won't open.
bool openAudio(AppState& a) {
    SDL_AudioSpec want{}, have{};
    want.freq = a.reqSampleRate;
    want.format = AUDIO_F32SYS;
    want.channels = 2;
    want.samples = static_cast<Uint16>(a.reqBlockSize);
    want.callback = audioCb;
    want.userdata = &a;
    a.audioDev = SDL_OpenAudioDevice(nullptr, 0, &want, &have, 0);
    if (a.audioDev == 0) {
        std::fprintf(stderr, "[retroplug-sdl] SDL_OpenAudioDevice(%d Hz, %d frames) failed: %s (muted)\n",
                     a.reqSampleRate, a.reqBlockSize, SDL_GetError());
        return false;
    }
    a.sampleRate = have.freq;
    a.audioL.assign(have.samples, 0.0f);
    a.audioR.assign(have.samples, 0.0f);
    return true;
}

std::string audioCfgPath(AppState& a) { return a.hostSvc.configDir() + "/audio.cfg"; }

void loadAudioConfig(AppState& a) {
    if (FILE* f = std::fopen(audioCfgPath(a).c_str(), "r")) {
        int sr = 0, bs = 0;
        if (std::fscanf(f, "%d %d", &sr, &bs) == 2 && sr > 0 && bs > 0) { a.reqSampleRate = sr; a.reqBlockSize = bs; }
        std::fclose(f);
    }
}

void saveAudioConfig(AppState& a) {
    if (FILE* f = std::fopen(audioCfgPath(a).c_str(), "w")) {
        std::fprintf(f, "%d %d\n", a.reqSampleRate, a.reqBlockSize);
        std::fclose(f);
    }
}

// Live audio reconfigure (the Audio settings submenu): stop the device, take the Engine back from the
// audio thread, re-rate it, re-open at the new rate/block, hand it back — the plugin's deactivate →
// setSampleRate → activate handoff. Then persist. Called on the UI thread.
void reconfigureAudio(AppState& a, int sampleRate, int blockSize) {
    if (sampleRate == a.reqSampleRate && blockSize == a.reqBlockSize && a.audioDev) return; // no-op
    if (a.audioDev) { SDL_PauseAudioDevice(a.audioDev, 1); SDL_CloseAudioDevice(a.audioDev); a.audioDev = 0; }
    a.invoker.setAudioThreadOwns(false);
    a.invoker.drainInto(a.engine);
    a.reqSampleRate = sampleRate;
    a.reqBlockSize  = blockSize;
    a.engine.setSampleRate(sampleRate); // re-rate live cores (safe — audio thread stopped)
    if (openAudio(a)) {
        a.invoker.setAudioThreadOwns(true);
        SDL_PauseAudioDevice(a.audioDev, 0);
    }
    saveAudioConfig(a);
    std::fprintf(stderr, "[retroplug-sdl] audio reconfigured: %d Hz, %d frames\n", a.reqSampleRate, a.reqBlockSize);
}

