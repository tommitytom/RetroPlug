bool readReady(TjsHostRuntime& host) {
    JSContext* ctx = host.context();
    JSValue g = JS_GetGlobalObject(ctx);
    JSValue v = JS_GetPropertyStr(ctx, g, "__rp_ready");
    const bool r = JS_ToBool(ctx, v) > 0;
    JS_FreeValue(ctx, v);
    JS_FreeValue(ctx, g);
    return r;
}

// Call globalThis[name](arg?) on the control-plane context (main thread). Returns the string result, or
// "" for non-string / missing / exception. Mirrors PluginDSP::callGlobal (used for autoload here).
std::string callGlobal(TjsHostRuntime& host, const char* name, const char* arg) {
    JSContext* ctx = host.context();
    JSValue g  = JS_GetGlobalObject(ctx);
    JSValue fn = JS_GetPropertyStr(ctx, g, name);
    std::string out;
    if (JS_IsFunction(ctx, fn)) {
        JSValue argv[1];
        int argc = 0;
        if (arg) { argv[0] = JS_NewString(ctx, arg); argc = 1; }
        JSValue ret = JS_Call(ctx, fn, g, argc, argc ? argv : nullptr);
        if (argc) JS_FreeValue(ctx, argv[0]);
        if (JS_IsException(ret)) {
            JSValue exc = JS_GetException(ctx);
            const char* s = JS_ToCString(ctx, exc);
            std::fprintf(stderr, "[retroplug-sdl] %s threw: %s\n", name, s ? s : "?");
            if (s) JS_FreeCString(ctx, s);
            JS_FreeValue(ctx, exc);
        } else if (JS_IsString(ret)) {
            const char* s = JS_ToCString(ctx, ret);
            if (s) { out = s; JS_FreeCString(ctx, s); }
        } else if (JS_IsBool(ret)) {
            out = JS_ToBool(ctx, ret) > 0 ? "true" : "false";
        }
        JS_FreeValue(ctx, ret);
    }
    JS_FreeValue(ctx, fn);
    JS_FreeValue(ctx, g);
    return out;
}

bool hasGlobalFunction(JSContext* ctx, const char* name) {
    JSValue g = JS_GetGlobalObject(ctx);
    JSValue v = JS_GetPropertyStr(ctx, g, name);
    const bool ok = JS_IsFunction(ctx, v);
    JS_FreeValue(ctx, v);
    JS_FreeValue(ctx, g);
    return ok;
}

// ---- __rp_* window hooks (PluginUI's window-op seam, single-instance) ------------------------------
// The UI optional-chains these, so anything we omit is simply inert. We provide the handful a handheld
// standalone needs; the render-job hooks are left to a later milestone.

JSValue jsQuitWindow(JSContext*, JSValueConst, int, JSValueConst*) {
    if (g_app) g_app->running = false;
    return JS_UNDEFINED;
}
// A fullscreen (handheld) window is WM-controlled → the UI fits its grid via zoom rather than resizing a
// fixed panel. A desktop windowed session is ours to size, so the App's fit-to-grid effect drives resizes.
JSValue jsIsWindowSizeControlled(JSContext* ctx, JSValueConst, int, JSValueConst*) {
    return JS_NewBool(ctx, g_app ? g_app->fullscreen : 1);
}
// __rp_setWindowSize(w, h): grow/shrink the window to the grid (desktop only). Mirrors the DPF standalone,
// where setSize() → the platform resize callback reallocs the LVGL buffer + emits "resize"; SDL gives us no
// such callback, so resizeWindow does it all inline. Inert on a fullscreen handheld (the WM owns the panel).
JSValue jsSetWindowSize(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (!g_app || g_app->fullscreen || argc < 2) return JS_UNDEFINED;
    std::uint32_t w = 0, h = 0;
    JS_ToUint32(ctx, &w, argv[0]);
    JS_ToUint32(ctx, &h, argv[1]);
    if (w != 0 && h != 0 && (w != g_app->width || h != g_app->height)) resizeWindow(*g_app, w, h);
    return JS_UNDEFINED;
}
JSValue jsSetWindowTitle(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (g_app && g_app->window && argc >= 1) {
        const char* t = JS_ToCString(ctx, argv[0]);
        if (t && *t) SDL_SetWindowTitle(g_app->window, t);
        if (t) JS_FreeCString(ctx, t);
    }
    return JS_UNDEFINED;
}
JSValue jsOpenPath(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (argc >= 1) {
        const char* p = JS_ToCString(ctx, argv[0]);
        if (p && *p) { const std::string cmd = "xdg-open \"" + std::string(p) + "\" &"; (void)std::system(cmd.c_str()); }
        if (p) JS_FreeCString(ctx, p);
    }
    return JS_UNDEFINED;
}

// __rp_getAudioConfig(): { sampleRate, blockSize, outChannels } — the live standalone audio device config,
// for the Audio settings submenu to display the current values.
JSValue jsGetAudioConfig(JSContext* ctx, JSValueConst, int, JSValueConst*) {
    JSValue o = JS_NewObject(ctx);
    if (g_app) {
        JS_SetPropertyStr(ctx, o, "sampleRate",  JS_NewInt32(ctx, g_app->reqSampleRate));
        JS_SetPropertyStr(ctx, o, "blockSize",   JS_NewInt32(ctx, g_app->reqBlockSize));
        JS_SetPropertyStr(ctx, o, "outChannels", JS_NewInt32(ctx, g_app->reqOutChannels));
    }
    return o;
}

// __rp_setAudioConfig(sampleRate, blockSize, outChannels?): re-open the audio device with new params on the
// fly (and persist them). Reuses the deactivate→re-rate→reactivate handoff the plugin does for a host SR
// change. outChannels is optional (older UI bundles omit it) — 2/4/6/8; anything else keeps the current count.
JSValue jsSetAudioConfig(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (g_app && argc >= 2) {
        int sr = 0, bs = 0, ch = g_app->reqOutChannels;
        JS_ToInt32(ctx, &sr, argv[0]);
        JS_ToInt32(ctx, &bs, argv[1]);
        if (argc >= 3) { int c = 0; JS_ToInt32(ctx, &c, argv[2]); if (c >= 2 && c <= 8 && (c % 2) == 0) ch = c; }
        if (sr > 0 && bs > 0) reconfigureAudio(*g_app, sr, bs, ch);
    }
    return JS_UNDEFINED;
}

void installWindowHooks(JSContext* ctx) {
    JSValue g = JS_GetGlobalObject(ctx);
    auto bind = [&](const char* name, JSCFunction* fn, int len) {
        JS_SetPropertyStr(ctx, g, name, JS_NewCFunction(ctx, fn, name, len));
    };
    bind("__rp_quitWindow", jsQuitWindow, 0);
    bind("__rp_isWindowSizeControlled", jsIsWindowSizeControlled, 0);
    bind("__rp_setWindowSize", jsSetWindowSize, 2);
    bind("__rp_setWindowTitle", jsSetWindowTitle, 1);
    bind("__rp_openPath", jsOpenPath, 1);
    bind("__rp_getAudioConfig", jsGetAudioConfig, 0);
    bind("__rp_setAudioConfig", jsSetAudioConfig, 2);
    // Mark this as a standalone host so the UI shows the "Exit" menu row (a DAW hides it).
    JS_SetPropertyStr(ctx, g, "__rp_isStandalone", JS_NewBool(ctx, 1));
    JS_FreeValue(ctx, g);
}

