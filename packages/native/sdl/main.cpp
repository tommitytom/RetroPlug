bool bootControlPlane(AppState& a) {
    if (!a.host.init()) { std::fprintf(stderr, "[retroplug-sdl] TjsHostRuntime init failed\n"); return false; }
    JSContext* ctx = a.host.context();

    registerCoreBackends(a.factory);

    a.transport = std::make_unique<rpcpp::QuickJSTransport>(ctx, [](JSContext*, JSValue) {});
    a.server    = std::make_unique<BackendRpcServer>(*a.transport, rpcpp::QuickJSCodec{ctx});
    registerHostRpc(*a.server, a.hostSvc);
    registerEmulatorRpc(*a.server, a.engineSvc);
    registerDspKernelRpc(*a.server, a.engineSvc);
    a.server->addDiscoveryMethod();

    // globalThis[Symbol.for("plugin")] = { __rpcSend } — the namespace realBackend.ts targets.
    JSValue global = JS_GetGlobalObject(ctx);
    JSValue sym    = JS_NewSymbol(ctx, "plugin", /*is_global*/ 1);
    JSAtom atom    = JS_ValueToAtom(ctx, sym);
    JSValue ns     = JS_NewObjectProto(ctx, JS_NULL);
    BackendRpcServer* srv = a.server.get();
    a.host.bindRpcSend(ns, [srv](JSContext* sctx, JSValueConst req) -> JSValue {
        auto out = srv->processMessage(req);
        if (!out) return JS_NULL;
        return out->materialize(sctx);
    });
    JS_DefinePropertyValue(ctx, global, atom, ns, JS_PROP_C_W_E);
    JS_FreeAtom(ctx, atom);
    JS_FreeValue(ctx, sym);
    JS_FreeValue(ctx, global);

    // Systems bake the sample rate at construct — set it BEFORE the bundle composes / autoloads.
    a.engine.setSampleRate(a.sampleRate);

    a.host.evalModuleBytecode(rp_cp_bundle, rp_cp_bundle_size);
    for (int i = 0; i < 1000 && !readReady(a.host); ++i) a.host.pump();
    if (!readReady(a.host)) { std::fprintf(stderr, "[retroplug-sdl] control plane not ready\n"); return false; }
    return true;
}

bool setupUi(AppState& a) {
    lv_init();
    lv_tick_set_cb(sdlTicksCb);

    a.display = lv_display_create(a.width, a.height);
    if (!a.display) return false;
    const lv_color_format_t cf = lv_display_get_color_format(a.display);
    const std::uint32_t stride = lv_draw_buf_width_to_stride(a.width, cf);
    a.drawBuf.assign(static_cast<std::size_t>(stride) * a.height, 0);
    lv_display_set_buffers(a.display, a.drawBuf.data(), nullptr, a.drawBuf.size(), LV_DISPLAY_RENDER_MODE_DIRECT);
    lv_display_set_flush_cb(a.display, flushCb);

    a.group = lv_group_create();
    lv_group_set_default(a.group);
    a.keypad = lv_indev_create();
    lv_indev_set_type(a.keypad, LV_INDEV_TYPE_KEYPAD);
    lv_indev_set_read_cb(a.keypad, keypadReadCb);
    lv_indev_set_driver_data(a.keypad, &a);
    lv_indev_set_group(a.keypad, a.group);
    a.pointer = lv_indev_create();
    lv_indev_set_type(a.pointer, LV_INDEV_TYPE_POINTER);
    lv_indev_set_read_cb(a.pointer, pointerReadCb);
    lv_indev_set_driver_data(a.pointer, &a);

    if (!a.ui.init()) { std::fprintf(stderr, "[retroplug-sdl] LvglJsEngine init failed\n"); return false; }

    JSContext* ctx = a.ui.getContext();
    if (ctx && !hasGlobalFunction(ctx, "__rp_mountUI")) {
        if (a.ui.evalModuleBytecode(rp_ui_bundle, rp_ui_bundle_size) != 0) {
            std::fprintf(stderr, "[retroplug-sdl] failed to eval UI bundle\n");
            return false;
        }
    }
    a.ui.attachDisplay(); // → __rp_mountUI

    // Black out the screen + strip the theme chrome, and make the React-tree root track the screen (100%)
    // — same as PluginUI so nothing draws a border / inset / scrollbar.
    if (lv_obj_t* screen = lv_screen_active()) {
        lv_obj_set_style_bg_color(screen, lv_color_hex(0x000000), 0);
        lv_obj_set_style_bg_opa(screen, LV_OPA_COVER, 0);
        lv_obj_set_style_border_width(screen, 0, 0);
        lv_obj_set_style_radius(screen, 0, 0);
        lv_obj_set_style_pad_all(screen, 0, 0);
        lv_obj_remove_flag(screen, LV_OBJ_FLAG_SCROLLABLE);
    }
    if (lv_obj_t* win = GetWindowInstance()) {
        lv_obj_set_style_width(win, lv_pct(100), 0);
        lv_obj_set_style_height(win, lv_pct(100), 0);
    }
    if (ctx) installWindowHooks(ctx);
    return true;
}

bool setupSdl(AppState& a) {
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_AUDIO | SDL_INIT_GAMECONTROLLER) != 0) {
        std::fprintf(stderr, "[retroplug-sdl] SDL_Init failed: %s\n", SDL_GetError());
        return false;
    }
    Uint32 winFlags = 0;
    if (std::getenv("RETROPLUG_SDL_FULLSCREEN")) winFlags |= SDL_WINDOW_FULLSCREEN;
    a.window = SDL_CreateWindow("RetroPlug", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
                                a.width, a.height, winFlags);
    if (!a.window) { std::fprintf(stderr, "[retroplug-sdl] SDL_CreateWindow failed: %s\n", SDL_GetError()); return false; }
    a.renderer = SDL_CreateRenderer(a.window, -1, SDL_RENDERER_SOFTWARE);
    if (!a.renderer) { std::fprintf(stderr, "[retroplug-sdl] SDL_CreateRenderer failed: %s\n", SDL_GetError()); return false; }
    a.texture = SDL_CreateTexture(a.renderer, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STREAMING,
                                  a.width, a.height);
    if (!a.texture) { std::fprintf(stderr, "[retroplug-sdl] SDL_CreateTexture failed: %s\n", SDL_GetError()); return false; }

    // Audio: apply any persisted rate/block (the Audio settings submenu) then open before boot so the
    // obtained rate seeds the Engine. The dummy driver (headless) still fires the callback, so the
    // emulator advances even with no device.
    loadAudioConfig(a);
    openAudio(a);
    return true;
}

void present(AppState& a) {
    if (!a.dirty) return; // nothing redrew this frame — leave the screen as-is (huge idle CPU saving)
    const int stride = static_cast<int>(lv_draw_buf_width_to_stride(a.width, lv_display_get_color_format(a.display)));
    // Upload only the changed region (clamped) from the draw buffer; the streaming texture keeps the rest.
    int x1 = std::max(0, (int)a.dirtyRect.x1), y1 = std::max(0, (int)a.dirtyRect.y1);
    int x2 = std::min((int)a.width - 1, (int)a.dirtyRect.x2), y2 = std::min((int)a.height - 1, (int)a.dirtyRect.y2);
    if (x2 >= x1 && y2 >= y1) {
        SDL_Rect rect{x1, y1, x2 - x1 + 1, y2 - y1 + 1};
        const std::uint8_t* src = a.drawBuf.data() + static_cast<std::size_t>(y1) * stride + static_cast<std::size_t>(x1) * 4;
        SDL_UpdateTexture(a.texture, &rect, src, stride);
    }
    SDL_RenderCopy(a.renderer, a.texture, nullptr, nullptr);
    SDL_RenderPresent(a.renderer);
    a.dirty = false;
}

void handleEvents(AppState& a) {
    SDL_Event ev;
    while (SDL_PollEvent(&ev)) {
        switch (ev.type) {
            case SDL_QUIT: a.running = false; break;
            case SDL_KEYDOWN:
            case SDL_KEYUP: {
                // While the file browser is open, keyboard drives it (desktop testing) — not the React UI.
                if (a.fb.active) {
                    if (ev.type == SDL_KEYDOWN) {
                        switch (ev.key.keysym.sym) {
                            case SDLK_UP:     fbMove(a, -1); break;
                            case SDLK_DOWN:   fbMove(a, 1); break;
                            case SDLK_PAGEUP: fbMove(a, -8); break;
                            case SDLK_PAGEDOWN: fbMove(a, 8); break;
                            case SDLK_RETURN: fbActivate(a); break;
                            case SDLK_ESCAPE: fbCancel(a); break;
                            default: break;
                        }
                    }
                    break;
                }
                std::uint32_t lv, dpf;
                if (mapSdlKey(ev.key.keysym.sym, lv, dpf)) feedKey(a, lv, dpf, ev.type == SDL_KEYDOWN);
                break;
            }
            case SDL_MOUSEMOTION: a.mousePos = {ev.motion.x, ev.motion.y}; break;
            case SDL_MOUSEBUTTONDOWN:
            case SDL_MOUSEBUTTONUP:
                a.mousePos = {ev.button.x, ev.button.y};
                a.mouseDown = ev.type == SDL_MOUSEBUTTONDOWN;
                break;
            default: break;
        }
    }
}

