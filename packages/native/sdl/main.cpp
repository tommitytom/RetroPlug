// A native on-screen file browser (there is no OS file dialog on a handheld). Renders on LVGL's top
// layer — above the React UI, outside its tree — and is driven directly by the gamepad/keyboard, so it
// never touches the React focus system. Answers the UI's __rp_openFileBrowser and reports back via
// __rp_onFileBrowserResult (the resolver realBackend.ts installs).
struct Entry { std::string name; bool isDir; };
struct FileBrowser {
    bool active = false;
    lv_obj_t* overlay = nullptr;
    lv_obj_t* list = nullptr;
    lv_obj_t* titleLabel = nullptr;
    std::string title;
    std::string dir;
    std::vector<std::string> patterns; // globs, e.g. {"*.gb","*.gbc"}; empty = all files
    bool saving = false;
    std::vector<Entry> entries;        // current dir contents (".." first)
    std::vector<lv_obj_t*> rows;       // list buttons, parallel to entries
    int sel = 0;
};

// Whole-process state, reached by the LVGL indev read callbacks (via driver_data), the SDL audio
// callback (via userdata), and the __rp_* window hooks (single instance → a file-scope pointer is fine,
// unlike the plugin's per-context routing for multi-instance DAWs).
struct AppState {
    // --- the shared runtime + backend graph (PluginDSP's control plane) ---
    TjsHostRuntime host;
    Engine         engine;
    SystemFactory  factory;
    QueuedInvoker  invoker{engine, engine.registry()};
    HostRpcService   hostSvc;
    EngineRpcService engineSvc{engine, factory, invoker};
    std::unique_ptr<rpcpp::QuickJSTransport> transport;
    std::unique_ptr<BackendRpcServer>        server;

    // --- the UI display layer (PluginUI), on the SAME host ---
    LvglJsEngine  ui{host};   // external-host ctor: adds only the LVGL layer, never shuts host down
    lv_display_t* display = nullptr;
    std::vector<std::uint8_t> drawBuf;
    lv_group_t*   group = nullptr;
    lv_indev_t*   keypad = nullptr;
    lv_indev_t*   pointer = nullptr;

    // synthetic input state the indev read callbacks pull from
    std::deque<std::uint32_t> keyQueue;   // pending LVGL key codes (keypad indev)
    lv_point_t mousePos{0, 0};
    bool       mouseDown = false;

    FileBrowser fb;   // native file-picker overlay (answers __rp_openFileBrowser)

    // --- SDL shell ---
    SDL_Window*   window = nullptr;
    SDL_Renderer* renderer = nullptr;
    SDL_Texture*  texture = nullptr;
    SDL_AudioDeviceID audioDev = 0;
    retroplug::GamepadManager gamepad;

    std::uint32_t width = 640;
    std::uint32_t height = 480;
    bool running = true;

    // audio scratch (pre-sized to the device block, so the callback never allocates)
    std::vector<float> audioL, audioR;
    double sampleRate = 48000.0;   // obtained device rate (drives the Engine)
    int    reqSampleRate = 48000;  // requested (UI-configurable) rate + block, persisted to audio.cfg
    int    reqBlockSize  = 2048;

    // Present only when LVGL actually redrew: the flush cb unions the changed area here; the loop skips
    // the SDL texture upload + blit entirely on idle frames (a static menu → ~0% CPU instead of a full
    // 640×480 upload every frame). dirty starts true so the first frame always shows.
    bool dirty = true;
    lv_area_t dirtyRect{0, 0, 0, 0};
};

AppState* g_app = nullptr;  // single instance

