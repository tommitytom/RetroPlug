// Every document buildGraph's goldens hold must PLAN on the engine. Two files hold them. golden/build-graph.json is the
// matrix of system sets, routings and host shapes the TS builder is held to (packages/retroplug/test/graph/
// build-graph-goldens.test.ts), with no roles; golden/build-graph-roles.json is buildGraph's own record of documents
// with protocol nodes, controllers and every MIDI routing mode (build-graph-role-goldens.test.ts). Those tests only
// compare documents. Here each distinct request is handed to a fresh Engine with the real packages (the script nodes
// among them, from the script bundle every Engine embeds), so a port name, a settings key or a node limit the planner
// refuses fails here for a shape no other suite runs: chained adds past rp.core.add's 16 inputs, a NES's ten channels,
// the Game Boy stems, link cables under every routing, the routing's outputs for thirty-three systems, and each
// protocol node type wired into the system node it feeds, an LSDj's serial-out decoder after its Game Boy, the N8 cart
// node, and the control surface's two nodes.
//
// The cores are real: each system node builds its own from the resources its settings name (docs/
// modular-graph-phase-c3-design.md section 6), so here each of a case's systems' ROMs is put in the engine's resource
// table and the document is pointed at those ids before it is handed over. A NES in the case's model carries its export
// mode as its node's construct-time setting, and the case's tap arm rides the request, so each NES must end in the mode
// it armed, or the one it was built in. Each plan then runs, and its blocks must fault no node, throw in no script node and drop no
// message: a document can plan and still wedge a linked group or a node's process, and the script host catches a
// script node's throw, counts it and runs the node again next block, rather than faulting. A build-graph.json plan runs
// one quiet block. A build-graph-roles.json plan runs twenty, with the transport playing, host MIDI on four channels
// and a control surface attached and pressed: a press waits in its link before block 0 (the node's first block, which
// discards what the link held) and another is staged for block 1, so the case holds both that no press from before the
// plan launches and that one staged after the surface settled does, and its protocol nodes send into the system inputs
// they feed while its controller launches into its cart or out of the host. What reaches a system input the engine does
// not hand back, so only the host's side has a floor: a controller sends its surface something, and one driving a real
// Game Boy sends the host its launch under the system it resolved. A document that drives the real cart is held on the
// other side of that fan-out: every byte its cart node pushed at the device is compared with what the system's own N8
// FIFO accepted, so the routed MIDI and the protocol nodes' generated bytes are pinned reaching the cart end to end.
// A Game Boy captures its serial out as its node's settings say, an LSDj's in a MIDI-out mode, but every core here
// runs mGB, which never plays the serial master (docs/modular-graph-phase-c2-design.md section 5), so a decoder's
// host MIDI is not counted on, and host MIDI under the controller's system is the controller's. The thirty-three
// systems under perSystem give rp.host.audio-out 33 buses, past the 32 it takes: those are refused instead. And since
// a C++ node reads only the settings fields it knows, ignoring any other, each system node's settings may name only
// fields its type's schema lists: a misspelt knob would plan, and do nothing.
//
// Run via `pnpm test:plugin engine-graph`.

