void UiTestHarness::pump(int iterations) {
    constexpr std::uint32_t kFrames = 1024; // ~23ms at 44.1kHz
    if (scratchL_.size() < kFrames) { scratchL_.resize(kFrames); scratchR_.resize(kFrames); }
    float* outs[2] = { scratchL_.data(), scratchR_.data() };
    for (int i = 0; i < iterations; ++i) {
        // Drain UI->DSP commands before processing, like PluginDSP::run. This is
        // how RPC button presses (keyboard input routed through the UI) reach the
        // emulator. We only need ButtonPress headless (ROMs are loaded directly,
        // not via the LoadRom/AddSystem commands).
        Command cmd;
        bool configMutated = false;
        bool projectLoaded = false;
        while (commands_.tryPop(cmd)) {
            if (cmd.kind == Command::Kind::ButtonPress) {
                const auto& bp = cmd.payload.buttonPress;
                if (SystemBase* sys = project_.findSystem(bp.systemId))
                    sys->pressButton(bp.button, bp.down);
            } else if (cmd.kind == Command::Kind::LoadProject) {
                // Mirror PluginDSP's LoadProject handler so a project committed
                // by the RPC service (after relinking) actually applies in-harness.
                ProjectConfig* config = cmd.payload.loadProject.config;
                if (config) {
                    const SystemId first = project_.loadFromConfig(*config);
                    focusedSystemId_.store(first);
                    project_.rebuildLinkGroups();
                    project_.onActivate(sampleRate_.load());
                    delete config;
                    // A whole-project replace: emit ProjectLoaded so the UI
                    // re-seeds its settings too (not just structure).
                    projectLoaded = true;
                }
            } else if (cmd.kind == Command::Kind::LoadRom) {
                // Mirror PluginDSP's LoadRom so menu-driven ROM loads (e.g. the
                // embedded loadMgb) apply in headless UI tests: adopt into an
                // empty project, else replace the focused system. The incoming
                // system is already onActivate'd by the RPC service.
                SystemBase* incoming = cmd.payload.loadRom.newSystem;
                if (incoming) {
                    if (project_.systems().empty()) {
                        project_.adoptSystem(incoming);
                        focusedSystemId_.store(incoming->id());
                    } else {
                        SystemId target = focusedSystemId_.load();
                        if (!project_.findSystem(target))
                            target = project_.systems().front()->id();
                        delete project_.swapSystem(target, incoming);
                        focusedSystemId_.store(incoming->id());
                    }
                    project_.rebuildLinkGroups();
                    configMutated = true;
                }
            } else if (cmd.kind == Command::Kind::SetZoom) {
                // Mirror PluginDSP's SetZoom: update the replica only, NO
                // config-changed echo — the UI owns zoom and edits it
                // optimistically. 0..6 (0 = inherit the user default).
                const std::uint8_t z = cmd.payload.setZoom.zoom;
                if (z <= 6) project_.config().settings.zoom = z;
            } else if (cmd.kind == Command::Kind::SetLayout) {
                // Mirror PluginDSP's SetLayout: replica only, no echo.
                project_.config().settings.layout = cmd.payload.setLayout.layout;
            } else if (cmd.kind == Command::Kind::SetMidiRouting) {
                // Mirror PluginDSP's SetMidiRouting: replica only, no echo.
                project_.config().settings.midiRouting = cmd.payload.setMidiRouting.routing;
            } else if (cmd.kind == Command::Kind::SetAudioRouting) {
                // Mirror PluginDSP's SetAudioRouting: replica only, no echo.
                project_.config().settings.audioRouting = cmd.payload.setAudioRouting.routing;
            } else if (cmd.kind == Command::Kind::SetFastBoot) {
                // Boolean config toggle. Mirrors PluginDSP's handler so the
                // cyclable Fast Boot menu row reflects in headless UI tests
                // (the real round-trip is DSP-thread only; here we apply it
                // directly and re-notify the UI, as with loadRom above).
                const auto& fb = cmd.payload.setFastBoot;
                if (SystemBase* sys = project_.findSystem(fb.id)) {
                    const auto cur = sys->fastBoot();
                    if (cur && *cur != fb.enabled) {
                        sys->setFastBoot(fb.enabled);
                        configMutated = true;
                    }
                }
            } else if (cmd.kind == Command::Kind::AddSystem) {
                // Mirror PluginDSP's AddSystem so the menu's "Add Instance" /
                // "Duplicate Instance" flows apply in headless UI tests. The
                // incoming system is already onActivate'd by the RPC service.
                SystemBase* incoming = cmd.payload.addSystem.newSystem;
                if (incoming) {
                    project_.adoptSystem(incoming);
                    project_.rebuildLinkGroups();
                    if (focusedSystemId_.load() == 0)
                        focusedSystemId_.store(incoming->id());
                    configMutated = true;
                }
            } else if (cmd.kind == Command::Kind::RemoveSystem) {
                // Mirror PluginDSP's RemoveSystem so "Remove Instance" applies.
                // No event-queue consumer headless — delete the released system
                // directly (the plugin hands it back to the UI thread to free).
                const SystemId removedId = cmd.payload.removeSystem.id;
                delete project_.removeSystemAndRelease(removedId);
                project_.rebuildLinkGroups();
                if (focusedSystemId_.load() == removedId) {
                    focusedSystemId_.store(project_.systems().empty()
                        ? SystemId{0} : project_.systems().front()->id());
                }
                configMutated = true;
            }
        }
        // ProjectLoaded supersedes ConfigChanged for the same drain — a load is
        // a superset re-seed, so fire only the one event (mirrors PluginUI.cpp).
        if (projectLoaded) notifyProjectLoaded();
        else if (configMutated) notifyConfigChanged();

        // Advance the emulator so framebuffers publish (no DSP thread headless),
        // matching the per-tick emulator advance the plugin's audio thread does.
        std::fill_n(scratchL_.data(), kFrames, 0.0f);
        std::fill_n(scratchR_.data(), kFrames, 0.0f);
        AudioBlockInfo info{ kFrames, sampleRate_.load(), 120.0, 0.0, false };
        project_.onProcess(info, outs);

        g_tickMs += 23; // keep UI tick roughly in step with the audio block
        if (bridge_) {
            bridge_->pumpAsync();
            bridge_->pumpMemorySnapshots();
        }
        if (engine_.getContext()) engine_.emit("frame", 0, nullptr);
        engine_.tick();
        lv_timer_handler();
    }
}

Snapshot UiTestHarness::snapshot() {
    Snapshot out;
    lv_obj_t* scr = lv_screen_active();
    if (!scr) return out;
    lv_draw_buf_t* snap = lv_snapshot_take(scr, LV_COLOR_FORMAT_ARGB8888);
    if (!snap) return out;
    out.width  = snap->header.w;
    out.height = snap->header.h;
    const std::size_t bytes = static_cast<std::size_t>(out.width) * out.height * 4;
    out.argb.assign(snap->data, snap->data + bytes);
    lv_draw_buf_destroy(snap);
    return out;
}

bool UiTestHarness::snapshotPng(const std::string& path) {
    Snapshot s = snapshot();
    if (s.argb.empty()) return false;
    std::vector<unsigned char> rgb(static_cast<std::size_t>(s.width) * s.height * 3);
    for (std::size_t i = 0, n = static_cast<std::size_t>(s.width) * s.height; i < n; ++i) {
        rgb[i * 3 + 0] = s.argb[i * 4 + 2]; // B,G,R,A -> R,G,B
        rgb[i * 3 + 1] = s.argb[i * 4 + 1];
        rgb[i * 3 + 2] = s.argb[i * 4 + 0];
    }
    return lodepng_encode24_file(rpcli::resolveHostPath(path).c_str(), rgb.data(), s.width, s.height) == 0;
}

// Live lv_binding_js components: walk the tree, keep objects whose user_data is a
// BasicComponent currently in comp_map (so non-component LVGL objects + freed
// entries are both excluded).
static std::unordered_set<BasicComponent*> validComponentSet() {
    std::unordered_set<BasicComponent*> valid;
    for (const auto& [uid, bc] : comp_map) if (bc) valid.insert(bc);
    return valid;
}

std::vector<std::uint8_t> UiTestHarness::readMemory(std::uint32_t id, int memType) {
    SystemBase* sys = project_.findSystem(static_cast<SystemId>(id));
    if (!sys) return {};
    rp::MemoryAccessor acc = sys->getMemory(static_cast<rp::MemoryType>(memType),
                                            rp::AccessType::Read);
    if (!acc.valid() || acc.size() == 0) return {};
    return std::vector<std::uint8_t>(acc.data(), acc.data() + acc.size());
}

std::size_t UiTestHarness::widgetCount() const {
    const auto valid = validComponentSet();
    std::vector<lv_obj_t*> objs;
    collectTree(lv_screen_active(), objs);
    std::size_t n = 0;
    for (lv_obj_t* o : objs) {
        auto* bc = static_cast<BasicComponent*>(lv_obj_get_user_data(o));
        if (bc && valid.count(bc)) ++n;
    }
    return n;
}

std::size_t UiTestHarness::countByType(int compType) const {
    const auto valid = validComponentSet();
    std::vector<lv_obj_t*> objs;
    collectTree(lv_screen_active(), objs);
    std::size_t n = 0;
    for (lv_obj_t* o : objs) {
        auto* bc = static_cast<BasicComponent*>(lv_obj_get_user_data(o));
        if (bc && valid.count(bc) && static_cast<int>(bc->type) == compType) ++n;
    }
    return n;
}

lv_obj_t* UiTestHarness::findFirstByType(int compType) const {
    const auto valid = validComponentSet();
    std::vector<lv_obj_t*> objs;
    collectTree(lv_screen_active(), objs);
    for (lv_obj_t* o : objs) {
        auto* bc = static_cast<BasicComponent*>(lv_obj_get_user_data(o));
        if (bc && valid.count(bc) && static_cast<int>(bc->type) == compType) return o;
    }
    return nullptr;
}

lv_obj_t* UiTestHarness::findByText(const std::string& text) const {
    std::vector<lv_obj_t*> objs;
    collectTree(lv_screen_active(), objs);
    for (lv_obj_t* o : objs) {
        if (!lv_obj_check_type(o, &lv_label_class)) continue; // live label: safe to read
        const char* t = lv_label_get_text(o);
        if (t && text == t) return o;
    }
    return nullptr;
}

lv_obj_t* UiTestHarness::findByTextContaining(const std::string& substr) const {
    std::vector<lv_obj_t*> objs;
    collectTree(lv_screen_active(), objs);
    for (lv_obj_t* o : objs) {
        if (!lv_obj_check_type(o, &lv_label_class)) continue;
        const char* t = lv_label_get_text(o);
        if (t && std::string(t).find(substr) != std::string::npos) return o;
    }
    return nullptr;
}

lv_obj_t* UiTestHarness::findByTestId(const std::string& name) const {
    auto it = testIds_.find(name);
    if (it == testIds_.end()) return nullptr;
    // Only return it if still live (its slot may have unmounted).
    std::vector<lv_obj_t*> objs;
    collectTree(lv_screen_active(), objs);
    for (lv_obj_t* o : objs) if (o == it->second) return o;
    return nullptr;
}

lv_obj_t* UiTestHarness::focusedObject() const {
    if (!keypad_) return nullptr;
    lv_group_t* g = lv_indev_get_group(keypad_); // the menu's group once claimed
    return g ? lv_group_get_focused(g) : nullptr;
}

WidgetInfo UiTestHarness::widgetInfo(lv_obj_t* obj) const {
    WidgetInfo wi;
    if (!obj) return wi;
    wi.found = true;
    lv_area_t a;
    lv_obj_get_coords(obj, &a); // absolute (screen) coordinates
    wi.x = a.x1;
    wi.y = a.y1;
    wi.width  = lv_area_get_width(&a);
    wi.height = lv_area_get_height(&a);
    wi.childCount = lv_obj_get_child_count(obj);
    if (lv_obj_check_type(obj, &lv_label_class)) {
        if (const char* t = lv_label_get_text(obj)) wi.text = t;
    }
    return wi;
}

void UiTestHarness::tapKey(std::uint32_t lvKey) {
    keyQueue_.push_back(lvKey);
    // Mirror PluginUI: also fire the JS "key" channel (press then release) for
    // handlers that live there (prompt/capture/Esc/game input). LVGL key code ->
    // DPF key code (the value runtime/lvgljs/input.ts expects).
    std::uint32_t dpf;
    switch (lvKey) {
        case LV_KEY_UP:    dpf = 0xE036; break;
        case LV_KEY_DOWN:  dpf = 0xE038; break;
        case LV_KEY_RIGHT: dpf = 0xE037; break;
        case LV_KEY_LEFT:  dpf = 0xE035; break;
        case LV_KEY_ENTER: dpf = 0x0D;   break;
        case LV_KEY_ESC:   dpf = 0x1B;   break;
        default:           dpf = lvKey;  break;
    }
    JSContext* ctx = engine_.getContext();
    auto emitKey = [&](bool press) {
        if (!ctx) return;
        JSValue args[2] = { JS_NewUint32(ctx, dpf), JS_NewBool(ctx, press) };
        engine_.emit("key", 2, args);
        JS_FreeValue(ctx, args[0]);
        JS_FreeValue(ctx, args[1]);
    };
    emitKey(true);
    pump(2);  // keypad indev: PRESSED then RELEASED through lv_timer_handler
    emitKey(false);
    pump(1);
}

void UiTestHarness::clickAt(std::int32_t x, std::int32_t y) {
    JSContext* ctx = engine_.getContext();
    auto emitMouse = [&](bool press) {
        if (!ctx) return;
        JSValue args[4] = { JS_NewUint32(ctx, 0), JS_NewBool(ctx, press),
                            JS_NewFloat64(ctx, x), JS_NewFloat64(ctx, y) };
        engine_.emit("mouse", 4, args);
        for (JSValue& v : args) JS_FreeValue(ctx, v);
    };
    mousePos_  = { x, y };
    mouseDown_ = true;
    emitMouse(true);
    pump(2);  // register the press at (x,y)
    mouseDown_ = false;
    emitMouse(false);
    pump(2);  // release -> LVGL fires CLICKED -> onClick
}

