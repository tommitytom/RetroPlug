// LVGL is built in custom-global mode (LV_GLOBAL_CUSTOM): the application must
// provide lv_global_default(). In the plugin DPF's LVGLWidget supplies a
// per-instance one (deps/dpf-widgets/generic/LVGL.cpp); headless we need a
// single process-wide instance. Zero-initialized like DPF's calloc; lv_init()
// populates it. Leaked intentionally (process-lifetime singleton).
extern "C" lv_global_t* lv_global_default(void) {
    static lv_global_t* g = static_cast<lv_global_t*>(std::calloc(1, sizeof(lv_global_t)));
    return g;
}

