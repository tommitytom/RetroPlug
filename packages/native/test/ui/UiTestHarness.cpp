bool Snapshot::isFlat() const {
    if (argb.size() < 8) return true;
    const std::uint32_t first = *reinterpret_cast<const std::uint32_t*>(argb.data());
    for (std::size_t i = 4; i + 4 <= argb.size(); i += 4)
        if (*reinterpret_cast<const std::uint32_t*>(argb.data() + i) != first)
            return false;
    return true;
}

UiTestHarness::UiTestHarness(std::uint32_t width, std::uint32_t height)
    : width_(width), height_(height) {}

UiTestHarness::~UiTestHarness() {
    // Mirror PluginUI's teardown ordering: drop the bridge, clean the widget
    // tree while the JS context is still alive (so delete events drain safely),
    // then shut the engine and tear down the LVGL display.
    bridge_.reset();
    if (lv_obj_t* scr = lv_screen_active()) lv_obj_clean(scr);
    engine_.shutdown();
    if (keypad_)  lv_indev_delete(keypad_);
    if (pointer_) lv_indev_delete(pointer_);
    if (display_) lv_display_delete(display_);
    if (group_)   lv_group_delete(group_);
    recentFiles_.reset();
    userConfig_.reset();
    if (!recentDir_.empty() || !userConfigDir_.empty()) {
        std::error_code ec;
        if (!recentDir_.empty())     std::filesystem::remove_all(recentDir_, ec);
        if (!userConfigDir_.empty()) std::filesystem::remove_all(userConfigDir_, ec);
    }
    if (g_active == this) g_active = nullptr;
}

bool UiTestHarness::boot() {
    if (booted_) return true;
    g_active = this;

    // --- LVGL: the cheap, non-GL subset of LVGLWidget::init ----------------
    lv_init(); // idempotent in v9
    lv_tick_set_cb(tickCb);

    display_ = lv_display_create(width_, height_);
    if (!display_) return false;

    const lv_color_format_t cf = lv_display_get_color_format(display_);
    const std::uint32_t stride = lv_draw_buf_width_to_stride(width_, cf);
    drawBuf_.assign(static_cast<std::size_t>(stride) * height_, 0);
    lv_display_set_buffers(display_, drawBuf_.data(), nullptr, drawBuf_.size(),
                           LV_DISPLAY_RENDER_MODE_DIRECT);
    lv_display_set_flush_cb(display_, flushCb);

    group_ = lv_group_create();
    lv_group_set_default(group_);
    keypad_ = lv_indev_create();
    lv_indev_set_type(keypad_, LV_INDEV_TYPE_KEYPAD);
    lv_indev_set_read_cb(keypad_, keypadReadCb);
    lv_indev_set_driver_data(keypad_, this);
    lv_indev_set_group(keypad_, group_);
    pointer_ = lv_indev_create();
    lv_indev_set_type(pointer_, LV_INDEV_TYPE_POINTER);
    lv_indev_set_read_cb(pointer_, pointerReadCb);
    lv_indev_set_driver_data(pointer_, this);

    // --- JS engine + bridge + UI bundle ------------------------------------
    if (!engine_.init()) return false;

    // Match PluginUI: black screen background + root window tracks the display.
    if (lv_obj_t* scr = lv_screen_active()) {
        lv_obj_set_style_bg_color(scr, lv_color_hex(0x000000), 0);
        lv_obj_set_style_bg_opa(scr, LV_OPA_COVER, 0);
    }
    if (lv_obj_t* win = GetWindowInstance()) {
        lv_obj_set_style_width(win, lv_pct(100), 0);
        lv_obj_set_style_height(win, lv_pct(100), 0);
    }

    engine_.setParamWriteCallback([](uint32_t, float) {});
    engine_.registerParameter(0, "gain");

    installTestIdHook();

    // Recent-projects list in a per-harness temp dir so it never touches the real
    // user config. Wired into the bridge so the Recent menu + its RPCs work; the
    // onChange hook mirrors PluginUI, refetching the list in the UI on every edit.
    recentDir_ = std::filesystem::temp_directory_path() /
                 ("rp_ui_recent_" + std::to_string(reinterpret_cast<std::uintptr_t>(this)));
    std::error_code ec;
    std::filesystem::create_directories(recentDir_, ec);
    recentFiles_ = std::make_unique<RecentFiles>(recentDir_);
    recentFiles_->setOnChange([this] {
        if (engine_.getContext()) engine_.emit("recent-files-changed", 0, nullptr);
    });
    recentFiles_->start();

    // Per-harness UserConfig in a temp dir (same isolation as recentFiles_). The
    // reload callback emits "user-config-changed" exactly like PluginUI, so the
    // UI refetches and re-derives — e.g. live default-zoom propagation.
    userConfigDir_ = std::filesystem::temp_directory_path() /
                     ("rp_ui_cfg_" + std::to_string(reinterpret_cast<std::uintptr_t>(this)));
    std::filesystem::create_directories(userConfigDir_, ec);
    userConfig_ = std::make_unique<UserConfig>(userConfigDir_);
    userConfig_->setOnReload([this] {
        if (engine_.getContext()) engine_.emit("user-config-changed", 0, nullptr);
    });
    userConfig_->start();

    bridge_ = std::make_unique<PluginJsBridge>(
        engine_.host(), &project_, &commands_, &events_, &sampleRate_, &focusedSystemId_,
        userConfig_.get(), recentFiles_.get());
    // Route JS events out through this harness's display engine.
    bridge_->setEmitSink([this](const char* ch, int argc, JSValueConst* argv) {
        engine_.emit(ch, argc, argv);
    });

    // Stub the file browser so open*Browser RPCs succeed headlessly. The actual
    // chosen path is injected by the test via selectFile() -> onFileBrowserSelected.
    // Count the opens so a test can assert a browser did (or didn't) pop.
    browserOpenCount_ = 0;
    bridge_->setOpenFileBrowserCallback(
        [this](const char*, bool, const char*, const char*, const char*) { ++browserOpenCount_; });

    // Record standalone-quit requests so a UI test can assert the unsaved-changes
    // modal's Discard/Save → quit path fired.
    bridge_->setQuitCallback([this] { quitRequested_ = true; });

    if (engine_.evalModuleBytecode(ui_bundle, ui_bundle_size) != 0) return false;

    booted_ = true;
    return true;
}

void UiTestHarness::installTestIdHook() {
    JSContext* ctx = engine_.getContext();
    if (!ctx) return;
    JSValue g = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, g, "__rp_tagTestId",
                      JS_NewCFunction(ctx, jsTagTestId, "__rp_tagTestId", 2));
    JS_FreeValue(ctx, g);
}

std::uint32_t UiTestHarness::loadRom(const std::string& path, const std::string& savPath) {
    auto bytes = slurpBytes(path);
    if (detectRomFormat(bytes) != RomFormat::SameBoy)
        throw std::runtime_error("UiTestHarness::loadRom supports SameBoy ROMs only: " + path);

    SameBoyConfig cfg;
    cfg.romPath  = path;
    cfg.model    = SameBoyModel::CgbC;
    cfg.fastBoot = true;
    // Optional cartridge SRAM image (a .sav file): seeds battery RAM so LSDj
    // boots straight to the song screen (skips the 12-15s self-test). Read as
    // raw bytes — we deliberately do NOT link the LSDj sav codec into this
    // binary (its reflect-cpp instantiations clash with the RPC layer's and
    // break listSystems serialization). A prebuilt .sav (the golden corpus,
    // ../resources/roms/lsdj/<rom>.sav) is the input instead.
    if (!savPath.empty()) cfg.sram = slurpBytes(savPath);
    auto sys = std::make_unique<SameBoySystem>(
        project_.nextSystemId(), cfg, std::move(bytes));
    sys->onActivate(sampleRate_.load());
    const SystemId id = sys->id();
    project_.adoptSystem(sys.release());
    project_.rebuildLinkGroups();
    // Focus it so the UI routes keyboard input here (PluginUI drops keys when
    // focus is 0). The DSP does this on the AddSystem command; we load directly.
    focusedSystemId_.store(id);
    notifyConfigChanged(); // UI re-queries listSystems + getFocus
    return static_cast<std::uint32_t>(id);
}

void UiTestHarness::reopenEditor() {
    engine_.detachDisplay();
    pump(10);                 // flush LVGL async deletes from the unmount
    engine_.reattachDisplay();
    pump(30);                 // let the re-mounted React tree settle
}

