#!/usr/bin/env node
// GENERATOR (dev-time, not CI) for the risa song-record codec fixtures + goldens.
//
// Oracle: risa's OWN reference tooling under $RISA_SRC/tools/rom_patcher/src/save_manager —
//   parseSongRecord / makeRecord (record_codec.js) and the SaveImage catalog reader (catalog.js).
// It emits:
//   - test/risa/recordFixtures.ts   base64 of RAVER.risong's song_record.bin (a real record-v7 song)
//   - test/risa/golden/record_raver_v7.json     field-level summary of parseSongRecord(raver)
//   - test/risa/golden/record_blumarbl_v5.json  field-level summary of the v5 record inside v2_blumarbl
//
// The blumarbl (v5) record is NOT re-embedded — it already lives inside the test/risa/fixtures.ts
// v2_blumarbl battery; the test extracts it with recordBytesAt. We only need its golden here.
//
// It also asserts risa's own makeRecord(parseSongRecord(rec)) === rec for each record, so the byte
// round-trip the TS port must reproduce is proven on the oracle side first.
//
//   RISA_SRC=/workspaces/risa-v2.2.1-source node scripts/gen-risa-record-fixtures.mjs

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const RISA_SRC = process.env.RISA_SRC || "/workspaces/risa-v2.2.1-source";
const SM = join(RISA_SRC, "tools/rom_patcher/src/save_manager");

const { parseSongRecord, makeRecord } = await import(join(SM, "record_codec.js"));
const { SaveImage } = await import(join(SM, "catalog.js"));

function eq(a, b) {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
  return true;
}

// The same field-level summary the TS test computes from its own decodeRecord — must match byte-for-byte
// in JSON. Keep this in lockstep with test/risa/record.test.ts `summarize`.
function summarize(rec) {
  const countNonNull = (arr) => arr.reduce((n, x) => n + (x ? 1 : 0), 0);
  const songCells = rec.song.reduce(
    (n, track) => n + Array.from(track).reduce((m, c) => m + (c !== 0xff ? 1 : 0), 0),
    0,
  );
  const firstPhrase = rec.phrases.findIndex((p) => p);
  const firstInst = rec.instruments.findIndex((i) => i);
  return {
    name: rec.name,
    version: rec.recordVersion,
    tempoBpm: (rec.settings[0] << 8) | rec.settings[1],
    present: {
      songCells,
      chains: countNonNull(rec.chains),
      phrases: countNonNull(rec.phrases),
      aux: countNonNull(rec.auxPhrases[0]),
      instruments: countNonNull(rec.instruments),
      tables: countNonNull(rec.tables),
      grooves: countNonNull(rec.grooves),
    },
    spot: {
      phrase:
        firstPhrase < 0
          ? null
          : { idx: firstPhrase, row0: Array.from(rec.phrases[firstPhrase].slice(0, 4)) },
      instrument:
        firstInst < 0 ? null : { idx: firstInst, bytes: Array.from(rec.instruments[firstInst]) },
    },
  };
}

function golden(recordBytes, label) {
  const parsed = parseSongRecord(recordBytes);
  const remade = makeRecord(parsed);
  if (!eq(remade, recordBytes)) {
    throw new Error(`${label}: risa makeRecord(parseSongRecord(rec)) is NOT byte-identical — cannot use as a round-trip vector`);
  }
  const g = summarize(parsed);
  g.length = recordBytes.length;
  return g;
}

// --- RAVER (v7) from the .risong test resource ---------------------------------------------------
const risong = join(RISA_SRC, "tools/tests/resources/RAVER.risong");
const tmp = "/tmp/rp-risa-raver";
mkdirSync(tmp, { recursive: true });
execFileSync("unzip", ["-o", risong, "song_record.bin", "-d", tmp], { stdio: "ignore" });
const raver = new Uint8Array(readFileSync(join(tmp, "song_record.bin")));
if (raver[10] !== 7) throw new Error(`expected RAVER record version 7, got ${raver[10]}`);
const raverGold = golden(raver, "raver_v7");

// --- blumarbl (v5) — migrate the demo .srm, pull record 0 out of its catalog --------------------
const blumSav = "/tmp/rp-risa-blumarbl-v2.sav";
const blumSrm = join(RISA_SRC, "website/play/demos/blumarbl.srm");
if (!existsSync(blumSav)) {
  execFileSync("python3", [join(RISA_SRC, "tools/migrate_legacy_sav.py"), blumSrm, blumSav], {
    stdio: "ignore",
  });
}
const img = new SaveImage(new Uint8Array(readFileSync(blumSav)).buffer);
const blumRec = img.entries[0].recordBytes;
if (blumRec[10] !== 5) throw new Error(`expected blumarbl record version 5, got ${blumRec[10]}`);
const blumGold = golden(blumRec, "blumarbl_v5");

// --- emit --------------------------------------------------------------------------------------
const b64 = (u8) => Buffer.from(u8).toString("base64");
const fixturesTs = `// GENERATED by scripts/gen-risa-record-fixtures.mjs — do not hand-edit.
// A real risa song RECORD (the 16-byte header + payload of one catalog entry), for the song-payload
// codec tests. Source: tools/tests/resources/RAVER.risong -> song_record.bin (record version 7).
// The v5 blumarbl record is not re-embedded here — it lives inside test/risa/fixtures.ts's
// v2_blumarbl battery; the test extracts it with recordBytesAt.
const B64: Record<string, string> = {
  raver_v7:
    "${b64(raver)}",
};

function decodeB64(s: string): Uint8Array {
  const A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  const lut = new Int16Array(256).fill(-1);
  for (let i = 0; i < A.length; i++) lut[A.charCodeAt(i)] = i;
  let len = s.length;
  while (len > 0 && s[len - 1] === "=") len--;
  const out = new Uint8Array((len * 3) >> 2);
  let bits = 0, nbits = 0, o = 0;
  for (let i = 0; i < len; i++) {
    const v = lut[s.charCodeAt(i)];
    if (v < 0) continue;
    bits = (bits << 6) | v;
    nbits += 6;
    if (nbits >= 8) { nbits -= 8; out[o++] = (bits >> nbits) & 0xff; }
  }
  return out;
}

export type RecordFixtureKey = keyof typeof B64;
export const RECORD_FIXTURE_KEYS = Object.keys(B64) as RecordFixtureKey[];
export function recordBytes(key: RecordFixtureKey): Uint8Array {
  return decodeB64(B64[key]);
}
`;

writeFileSync(join(PKG, "test/risa/recordFixtures.ts"), fixturesTs);
mkdirSync(join(PKG, "test/risa/golden"), { recursive: true });
writeFileSync(join(PKG, "test/risa/golden/record_raver_v7.json"), JSON.stringify(raverGold, null, 2) + "\n");
writeFileSync(join(PKG, "test/risa/golden/record_blumarbl_v5.json"), JSON.stringify(blumGold, null, 2) + "\n");

console.log("raver_v7   :", JSON.stringify(raverGold));
console.log("blumarbl_v5:", JSON.stringify(blumGold));
console.log("wrote test/risa/recordFixtures.ts + golden/record_{raver_v7,blumarbl_v5}.json");
