// Generate packages/retroplug/src/risa/runtime/symbols.generated.ts from risa's cc65/VICE label files.
// risa emits build/risa-pal.lbl + build/ntsc/risa-ntsc.lbl (al <hex-addr> .<name>). The runtime-state
// variables all live in the NES internal 2 KB RAM ($0000-$07FF) and — verified here — sit at IDENTICAL
// addresses in the PAL and NTSC builds (the region only changes tables/timing, not the BSS/ZP layout),
// so one table serves both regions of a given risa version.
//
// Usage: RISA_SRC=/path/to/risa RISA_VERSION=2.3.0 node scripts/gen-risa-symbols.mjs
// (defaults: RISA_SRC=/workspaces/risa-v2.2.1-source, RISA_VERSION from its src/app_version.h).
// The run MERGES into the existing table: the named version is added or replaced, every other
// version already in the file is kept verbatim. So a new risa release is one run, not a rewrite.
//
// Getting the .lbl files: `make all` in a risa source tree (needs cc65 + python3) writes
// build/risa-pal.lbl + build/ntsc/risa-ntsc.lbl. A locally built ROM is NOT byte-identical to the
// developer's shipped binary (different cc65 build), so the addresses this emits must then be
// certified against the SHIPPED ROM on a real core: see test-native/risa-230-layout.test.ts, which
// boots it and asserts the decode is coherent and advances. Symbols that decode garbage fail there.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const RISA_SRC = process.env.RISA_SRC || "/workspaces/risa-v2.2.1-source";
const OUT = new URL("../src/risa/runtime/symbols.generated.ts", import.meta.url);

// cc65 prefixes C symbols with "_"; the runtime-state variables we read (see src/seq.h / ui_common.h).
const WANT = [
  "seq_mode", "seq_active", "seq_current_bpm", "song_queue_active",
  "bss_song_row", "bss_song_last_row", "bss_chain_idx", "bss_chain_row",
  "bss_phrase_idx", "bss_phrase_last_row", "zp_phrase_row",
  "bss_table_idx", "bss_last_inst", "apu_current_note", "kit_active_idx",
  "ui_current_screen", "ui_cursor_row", "ui_cursor_col", "ui_track",
];

function parseLbl(path) {
  const map = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    // `al 00037D ._seq_current_bpm`
    const m = line.match(/^al\s+([0-9A-Fa-f]+)\s+\.?_([A-Za-z0-9_]+)\s*$/);
    if (m) map[m[2]] = parseInt(m[1], 16);
  }
  return map;
}

const version = process.env.RISA_VERSION
  || (existsSync(`${RISA_SRC}/src/app_version.h`)
    ? (readFileSync(`${RISA_SRC}/src/app_version.h`, "utf8").match(/"(\d+\.\d+\.\d+)"/)?.[1] ?? "unknown")
    : "unknown");

const pal = parseLbl(`${RISA_SRC}/build/risa-pal.lbl`);
const ntscPath = `${RISA_SRC}/build/ntsc/risa-ntsc.lbl`;
const ntsc = existsSync(ntscPath) ? parseLbl(ntscPath) : null;

const out = {};
for (const name of WANT) {
  if (!(name in pal)) throw new Error(`symbol ${name} not in risa-pal.lbl (build risa first)`);
  if (ntsc && ntsc[name] !== pal[name]) {
    throw new Error(`symbol ${name} differs PAL(${pal[name]}) vs NTSC(${ntsc[name]}) — region-specific layout, revisit`);
  }
  out[name] = pal[name];
}

// Read back the versions already in the file so this run adds to them instead of replacing them.
// cc65 reshuffles the BSS/ZP layout between builds, so every risa version needs its own snapshot;
// dropping the old ones would un-support every cart but the one just generated.
function existingVersions() {
  if (!existsSync(OUT)) return {};
  const prev = {};
  const text = readFileSync(OUT, "utf8");
  for (const block of text.matchAll(/"(\d+\.\d+\.\d+)": \{([^}]*)\}/g)) {
    const fields = {};
    for (const f of block[2].matchAll(/(\w+): (0x[0-9a-f]+)/g)) fields[f[1]] = parseInt(f[2], 16);
    prev[block[1]] = fields;
  }
  return prev;
}

const table = existingVersions();
const replaced = version in table;
table[version] = out;
// Newest first, so the version a reader most likely wants is at the top.
const versions = Object.keys(table).sort((a, b) => {
  const [x, y] = [a.split(".").map(Number), b.split(".").map(Number)];
  return y[0] - x[0] || y[1] - x[1] || y[2] - x[2];
});

let ts = `// GENERATED by scripts/gen-risa-symbols.mjs - do not hand-edit. Internal-RAM addresses of risa's
// runtime-state variables (src/seq.h, src/ui_common.h), read per-block from the NES 2 KB RAM snapshot.
// Verified identical across the PAL and NTSC builds, so one table serves both regions. One entry per
// risa version: cc65 moves these between builds, so addresses are never shared across versions.

export interface RisaSymbols {\n`;
for (const name of WANT) ts += `  ${name}: number;\n`;
ts += `}\n\nexport const RISA_SYMBOLS: Record<string, RisaSymbols> = {\n`;
for (const v of versions) {
  ts += `  "${v}": {\n`;
  for (const name of WANT) {
    const addr = table[v][name];
    if (addr === undefined) throw new Error(`existing version ${v} is missing symbol ${name}; regenerate it too`);
    ts += `    ${name}: 0x${addr.toString(16)},\n`;
  }
  ts += `  },\n`;
}
ts += `};\n`;

writeFileSync(OUT, ts);
console.log(
  `${replaced ? "replaced" : "added"} risa ${version} in symbols.generated.ts ` +
    `(${WANT.length} symbols, PAL==NTSC${ntsc ? " verified" : ", NTSC lbl absent"}); ` +
    `file now covers ${versions.join(", ")}`,
);
