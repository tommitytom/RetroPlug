// Generate packages/retroplug/src/risa/runtime/symbols.generated.ts from risa's cc65/VICE label files.
// risa emits build/risa-pal.lbl + build/ntsc/risa-ntsc.lbl (al <hex-addr> .<name>). The runtime-state
// variables all live in the NES internal 2 KB RAM ($0000-$07FF) and — verified here — sit at IDENTICAL
// addresses in the PAL and NTSC builds (the region only changes tables/timing, not the BSS/ZP layout),
// so one table serves both regions of a given risa version.
//
// Usage: RISA_SRC=/path/to/risa RISA_VERSION=2.2.1 node scripts/gen-risa-symbols.mjs
// (defaults: RISA_SRC=/workspaces/risa-v2.2.1-source, RISA_VERSION from its src/app_version.h).
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const RISA_SRC = process.env.RISA_SRC || "/workspaces/risa-v2.2.1-source";
const OUT = new URL("../src/risa/runtime/symbols.generated.ts", import.meta.url);

// cc65 prefixes C symbols with "_"; the runtime-state variables we read (see src/seq.h / ui_common.h).
const WANT = [
  "seq_mode", "seq_active", "seq_current_bpm", "song_queue_active",
  "bss_song_row", "bss_song_last_row", "bss_chain_idx", "bss_chain_row",
  "bss_phrase_idx", "bss_phrase_last_row", "zp_phrase_row",
  "bss_table_idx", "bss_last_inst", "apu_current_note", "kit_active_idx",
  "ui_current_screen", "ui_cursor_row", "ui_cursor_col", "ui_track",
];

function parseLbl(path) {
  const map = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    // `al 00037D ._seq_current_bpm`
    const m = line.match(/^al\s+([0-9A-Fa-f]+)\s+\.?_([A-Za-z0-9_]+)\s*$/);
    if (m) map[m[2]] = parseInt(m[1], 16);
  }
  return map;
}

const version = process.env.RISA_VERSION
  || (existsSync(`${RISA_SRC}/src/app_version.h`)
    ? (readFileSync(`${RISA_SRC}/src/app_version.h`, "utf8").match(/"(\d+\.\d+\.\d+)"/)?.[1] ?? "unknown")
    : "unknown");

const pal = parseLbl(`${RISA_SRC}/build/risa-pal.lbl`);
const ntscPath = `${RISA_SRC}/build/ntsc/risa-ntsc.lbl`;
const ntsc = existsSync(ntscPath) ? parseLbl(ntscPath) : null;

const out = {};
for (const name of WANT) {
  if (!(name in pal)) throw new Error(`symbol ${name} not in risa-pal.lbl (build risa first)`);
  if (ntsc && ntsc[name] !== pal[name]) {
    throw new Error(`symbol ${name} differs PAL(${pal[name]}) vs NTSC(${ntsc[name]}) — region-specific layout, revisit`);
  }
  out[name] = pal[name];
}

const key = version.replace(/\./g, "_");
let ts = `// GENERATED by scripts/gen-risa-symbols.mjs — do not hand-edit. Internal-RAM addresses of risa's
// runtime-state variables (src/seq.h, src/ui_common.h), read per-block from the NES 2 KB RAM snapshot.
// Verified identical across the PAL and NTSC builds, so one table serves both regions.

export interface RisaSymbols {\n`;
for (const name of WANT) ts += `  ${name}: number;\n`;
ts += `}\n\nexport const RISA_SYMBOLS: Record<string, RisaSymbols> = {\n  "${version}": {\n`;
for (const name of WANT) ts += `    ${name}: 0x${out[name].toString(16)},\n`;
ts += `  },\n};\n`;

writeFileSync(OUT, ts);
console.log(`wrote symbols.generated.ts for risa ${version} (${WANT.length} symbols, PAL==NTSC${ntsc ? " verified" : " — NTSC lbl absent"})`);
