// Reconstruct the Everdrive N8 menu screen (256x224 RGBA) from a VramDump ('*v') + an ADDR_MENU_CHR read.
// A faithful port of krikzz edlink DEV_EDN8/MenuImage.cs (MakeImage/GetPixel/GetPal32). The N8 menu firmware
// pre-flattens the nametable, so `vram` is 1024 (tileIdx, attr) PAIRS (2 bytes each), NOT a raw PPU
// nametable + attribute table. `chr` is 512 tiles of NES 2bpp planar tile data (16 bytes/tile: bytes 0-7 =
// bitplane 0 rows, 8-15 = bitplane 1). Pure + host-agnostic; the CLI feeds the result to backend.pngEncode.

// The 64-entry NES master palette the N8 menu renders with, ported verbatim from edlink MenuImage.cs pal_nes
// (RGB triples). The 16 palette bytes from '*v' are indices 0..63 into this. (risa's NES_PALETTE is a
// different NES variant; this one matches what the N8 firmware/edlink produce, for menu-colour fidelity.)
// prettier-ignore
