const TILES_W = 32; // full 256-px width
const TILES_H = 28; // 224 lines (the N8 drops the top/bottom 8 scanlines of the 240-line frame)

export interface MenuImage {
  width: number;
  height: number;
  rgba: Uint8Array; // row-major RGBA8888, width*height*4 bytes (for backend.pngEncode)
}

/** Reconstruct the 256x224 menu screen. `chr` = 8192 bytes (ADDR_MENU_CHR read), `vram` = 2048, `palette` =
 *  16 (both from N8Menu.vramDump). See the port note above; mirrors edlink MenuImage.MakeImage exactly. */
export function menuScreenToRgba(chr: Uint8Array, vram: Uint8Array, palette: Uint8Array): MenuImage {
  const width = TILES_W * 8;
  const height = TILES_H * 8;
  const rgba = new Uint8Array(width * height * 4);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const tp = (x >> 3) + (y >> 3) * TILES_W;
      let tileIdx = vram[tp * 2];
      const attr = vram[tp * 2 + 1];
      if (attr & 4) tileIdx += 256; // attr bit 2 selects the 2nd 4 KB CHR bank
      const row = tileIdx * 16 + (y & 7);
      const bit = 7 - (x & 7);
      const p0 = (chr[row] >> bit) & 1;
      const p1 = (chr[row + 8] >> bit) & 1;
      const idx4 = ((attr & 3) << 2) | (p1 << 1) | p0; // attr bits 0-1 = palette group, bits from the pattern
      const nes = palette[idx4] & 0x3f; // NES master-palette index (6-bit)
      const o = (y * width + x) * 4;
      rgba[o] = PAL_NES[nes * 3];
      rgba[o + 1] = PAL_NES[nes * 3 + 1];
      rgba[o + 2] = PAL_NES[nes * 3 + 2];
      rgba[o + 3] = 0xff;
    }
  }
  return { width, height, rgba };
}
