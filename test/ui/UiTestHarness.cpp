// The active harness, for the static JS / LVGL trampolines (single runtime,
// single-threaded, one harness at a time — same recovery pattern as
// cli/TestHarness.cpp's g_activeImpl).
UiTestHarness* g_active = nullptr;

// Simulated millisecond clock. Advanced by pump() so LVGL timers fire
// deterministically without wall-clock dependence.
std::uint32_t g_tickMs = 0;
std::uint32_t tickCb() { return g_tickMs; }

// No-op flush: the draw buffer already holds the rendered pixels; there's no
// GL texture / window to push to. Just acknowledge so LVGL continues.
void flushCb(lv_display_t* disp, const lv_area_t*, uint8_t*) {
    lv_display_flush_ready(disp);
}

// Headless input devices read nothing (released). Present so the focus group +
// component creation (which calls lv_group_add_obj) work like in the plugin.
void keypadReadCb(lv_indev_t*, lv_indev_data_t* data) {
    data->state = LV_INDEV_STATE_RELEASED;
}

std::vector<std::uint8_t> slurpBytes(const std::string& path) {
    std::ifstream in(path, std::ios::binary | std::ios::ate);
    if (!in) throw std::runtime_error("cannot open " + path);
    const std::streamsize size = in.tellg();
    if (size <= 0) throw std::runtime_error("empty file: " + path);
    in.seekg(0, std::ios::beg);
    std::vector<std::uint8_t> buf(static_cast<std::size_t>(size));
    if (!in.read(reinterpret_cast<char*>(buf.data()), size))
        throw std::runtime_error("read failed: " + path);
    return buf;
}

// globalThis.__rp_tagTestId(uid, name): the UI calls this from a ref so we can
// map a stable name to the rendered lv_obj. uid is lv_binding_js's component id
// (a string); comp_map resolves it to the native instance. Inert in the real
// plugin (the function isn't installed there — the UI uses optional chaining).
JSValue jsTagTestId(JSContext* ctx, JSValueConst, int argc, JSValueConst* argv) {
    if (!g_active || argc < 2) return JS_UNDEFINED;
    const char* uid  = JS_ToCString(ctx, argv[0]);
    const char* name = JS_ToCString(ctx, argv[1]);
    if (uid && name) {
        auto it = comp_map.find(uid);
        if (it != comp_map.end() && it->second)
            g_active->recordTestId(name, it->second->instance);
    }
    if (uid)  JS_FreeCString(ctx, uid);
    if (name) JS_FreeCString(ctx, name);
    return JS_UNDEFINED;
}

