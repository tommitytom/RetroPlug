#!/usr/bin/env node
// Regenerates packages/retroplug/test/lsdj/fixtures.ts — a base64-embedded set of
// real LSDj .sav bytes for the pure-TS test tier (which cannot read disk). The
// matching decode reference lives as JSON under test/lsdj/golden/ and is imported
// directly (esbuild inlines JSON). Source savs are the committed liblsdj content
// fixtures under test/lsdj/savs/, so this is deterministic.
// Run: node tools/gen-lsdj-fixtures.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SAV_DIR = resolve(REPO, "packages/retroplug/test/lsdj/savs");

// The full set of liblsdj content-bearing savs — content-rich AND spanning EVERY
// decode branch (the version predicates sit at fmt 4/5/6/7/8/9/10/11/16, with
// nothing between; fmt12..15/17..22 share fmt11/16's paths). Goldens:
// test/lsdj/golden/<key>.json. Embedding all of them makes the pure-TS decode
// oracle self-sufficient — it covers the same branch surface as the (deletable)
// C++/liblsdj differential.
const FIXTURES = [
  ["lsdj499", "lsdj499.sav"], // fmt3  (fmt<4 vibrato, <5 synth, <8 command, <11 fill)
  ["lsdj620", "lsdj620.sav"], // fmt4
  ["lsdj668", "lsdj668.sav"], // fmt5  (>=5 synth resonance)
  ["lsdj671", "lsdj671.sav"], // fmt6  (wave length/speed ==6 branch)
  ["lsdj690", "lsdj690.sav"], // fmt7  (>=7 wave length/speed)
  ["all", "all.sav"], // fmt7, 2 stored projects
  ["happy_birthday", "happy_birthday.sav"], // fmt7
  ["lsdj732", "lsdj732.sav"], // fmt8  (>=8 command B-insert)
  ["lsdj790", "lsdj790.sav"], // fmt9  (>=9 wave loopPos)
  ["lsdj798", "lsdj798.sav"], // fmt10 (>=10 wave playMode)
  ["lsdj834", "lsdj834.sav"], // fmt11 (>=11 no fill; <16 synth nibble)
  ["lsdj888", "lsdj888.sav"], // fmt16 (>=16 synth nibble)
];

let body = `// GENERATED by tools/gen-lsdj-fixtures.mjs — do not edit by hand.
// Real LSDj .sav bytes (base64) for the pure-TS test tier. Decode references are
// the frozen C++ goldens under ./golden/<key>.json (import them directly).
const B64: Record<string, string> = {
`;
for (const [key, file] of FIXTURES) {
  const bytes = readFileSync(resolve(SAV_DIR, file));
  body += `  ${key}: "${bytes.toString("base64")}",\n`;
}
body += `};

declare function atob(s: string): string; // txiki/QuickJS + node globals (no DOM lib)

function decodeB64(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/** Real .sav bytes for a fixture key (lsdj499 | all | lsdj834 | lsdj888). */
export function savBytes(key: keyof typeof B64): Uint8Array {
  return decodeB64(B64[key]);
}

export const FIXTURE_KEYS = ${JSON.stringify(FIXTURES.map((f) => f[0]))} as const;
`;

const OUT = resolve(REPO, "packages/retroplug/test/lsdj/fixtures.ts");
writeFileSync(OUT, body);
console.error(`wrote ${OUT} (${FIXTURES.length} savs)`);
