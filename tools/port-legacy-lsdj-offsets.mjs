#!/usr/bin/env node
// One-off port of the old RetroPlug `ecs` LSDj offset table into the TS runtime reader. Fetches
// OffsetLookupData.h from the ecs branch and emits
// packages/retroplug/src/lsdj/runtime/legacyOffsets.generated.ts — a per-version map of the POSITIONAL
// block (active/phrase/chain/song) + the SONG cursor (cursorX/cursorY), for v4.0.0..9.2.x.
//
//   node tools/port-legacy-lsdj-offsets.mjs [path-to-OffsetLookupData.h]
//
// With no arg it fetches the file from GitHub. The old table keyed offsets by ROM hash → version →
// offset group; we collapse that to version → offsets, preferring the untagged (mainline/stable) build
// when a version has several. The old table has NO screen/tempo (those were computed live by
// OffsetCalculator), so this port carries only what the table stored. Screen/tempo for these older
// versions come from the detector's driftShifts where covered, else stay unknown.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const URL = "https://raw.githubusercontent.com/tommitytom/RetroPlug/ecs/src/lsdj/OffsetLookupData.h";
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../packages/retroplug/src/lsdj/runtime/legacyOffsets.generated.ts");

const src = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(URL)).text();

// OFFSET_GROUPS: rows of [active, phrase, chain, song, cursorX, cursorY].
const gblock = src.slice(src.indexOf("OFFSET_GROUPS = {"), src.indexOf("};", src.indexOf("OFFSET_GROUPS")));
const groups = [...gblock.matchAll(/\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}/g)].map((m) => m.slice(1).map(Number));

// VERSION_LOOKUP: hash → { {major,minor,patch}, group, tag? }. Iterate in file order (ascending version).
const vblock = src.slice(src.indexOf("VERSION_LOOKUP = {"));
const vers = [...vblock.matchAll(/semver::version\s*\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\},\s*(\d+)(?:,\s*"([^"]*)")?/g)].map((m) => ({
  major: +m[1], minor: +m[2], patch: +m[3], group: +m[4], tag: m[5] || "",
}));

// Collapse to version → offsets. Prefer the untagged (mainline) entry; else the first seen. A tagged
// fork (arduinoboy) whose layout differs is intentionally NOT keyed here — it keys as "x.y.z-<build>"
// from the title and falls back to the modern band / unknown, rather than inheriting the mainline block.
const byVersion = new Map();
for (const v of vers) {
  const key = `${v.major}.${v.minor}.${v.patch}`;
  const g = groups[v.group];
  if (!g) continue;
  const existing = byVersion.get(key);
  if (!existing || (existing.tag && !v.tag)) byVersion.set(key, { g, tag: v.tag });
}

const cmp = (a, b) => a.split(".").map(Number).reduce((acc, n, i) => acc || n - +b.split(".")[i], 0);
const keys = [...byVersion.keys()].sort(cmp);
const rows = keys.map((k) => {
  const [active, phrase, chain, song, curCol, curRow] = byVersion.get(k).g;
  return `  ${JSON.stringify(k)}: [${active}, ${phrase}, ${chain}, ${song}, ${curCol}, ${curRow}],`;
});

const out = `// GENERATED by tools/port-legacy-lsdj-offsets.mjs — do not edit by hand.
//
// Ported from the old RetroPlug \`ecs\` OffsetLookupData.h (per-ROM-hash → version → offset group),
// collapsed to version → [active, phrase, chain, song, songCursorCol, songCursorRow]. All WRAM-relative
// (addr - 0xC000). Covers v4.0.0..9.2.x (the range the original supported); the modern band + detector
// (offsets.ts / driftShifts.generated.ts) cover 9.3+. Cross-validated: for versions present in both
// this table and the detector, (songCursorCol - 0x41E) equals the detector's drift shift exactly.
//
// The old table stored NO screen/tempo (OffsetCalculator computed those live), so this carries only the
// positional block + the SONG cursor. Screen/tempo for these versions come from driftShifts where the
// version is covered, else resolve to null (unknown).
//
// Key = "major.minor.patch" (mainline build; tagged forks like arduinoboy are excluded — they key
// as "x.y.z-<build>" and fall back). Regenerate: node tools/port-legacy-lsdj-offsets.mjs
export const legacyOffsets: Record<string, readonly [number, number, number, number, number, number]> = {
${rows.join("\n")}
};
`;

writeFileSync(OUT, out);
console.log(`[port] wrote ${OUT} (${keys.length} versions, v${keys[0]}..v${keys[keys.length - 1]})`);
